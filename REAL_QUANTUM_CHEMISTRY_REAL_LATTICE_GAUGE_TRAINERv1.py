def detect_device() -> Tuple[Any, str]:
    if not HAS_TORCH:
        return None, "NO_TORCH"
    if torch.cuda.is_available():
        name = torch.cuda.get_device_name(0).lower()
        if any(k in name for k in ("amd", "radeon", "instinct")):
            return torch.device("cuda"), "AMD_ROCM"
        return torch.device("cuda"), "NVIDIA_CUDA"
    for mod, attr, tag in (
        ("intel_extension_for_pytorch", "xpu", "INTEL_XPU"),
        ("torch_npu", "npu", "HUAWEI_NPU"),
    ):
        try:
            __import__(mod)
            if hasattr(torch, attr) and getattr(torch, attr).is_available():
                return torch.device(attr), tag
        except ImportError:
            pass
    if getattr(torch.backends, "mps", None) and torch.backends.mps.is_available():
        return torch.device("mps"), "APPLE_MPS"
    return torch.device("cpu"), "CPU"


def dist_backend(tag: str) -> str:
    return {"NVIDIA_CUDA": "nccl", "AMD_ROCM": "nccl",
            "HUAWEI_NPU": "hccl", "INTEL_XPU": "ccl"}.get(tag, "gloo")


def setup_ddp() -> Tuple[Any, str, int, int]:
    dev, tag = detect_device()
    if dev is None:
        return None, tag, 0, 1
    if "RANK" in os.environ and "WORLD_SIZE" in os.environ:
        lr = int(os.environ.get("LOCAL_RANK", os.environ["RANK"]))
        if dev.type == "cuda":
            torch.cuda.set_device(lr); dev = torch.device("cuda", lr)
        elif dev.type == "xpu":
            torch.xpu.set_device(lr)
        elif dev.type == "npu":
            import torch_npu; torch_npu.npu.set_device(lr)
        dist.init_process_group(backend=dist_backend(tag))
        return dev, tag, dist.get_rank(), dist.get_world_size()
    return dev, tag, 0, 1


def is_dist() -> bool:
    return HAS_TORCH and dist.is_available() and dist.is_initialized()


def is_main() -> bool:
    return (not is_dist()) or dist.get_rank() == 0


def cleanup_ddp():
    if is_dist():
        dist.barrier(); dist.destroy_process_group()


@contextlib.contextmanager
def amp_ctx(dev, tag: str, dtype, enabled: bool = True):
    if not enabled or dev is None or dev.type in ("cpu", "mps"):
        yield; return
    dt = "cuda" if tag in ("NVIDIA_CUDA", "AMD_ROCM") else dev.type
    try:
        with torch.autocast(device_type=dt, dtype=dtype, enabled=True):
            yield
    except Exception:
        yield


