def torch_plaquette_features(links: Tensor) -> Tensor:
    """
    links: (B, D, L, L, L, L, 3, 3) complex
    returns gauge-invariant features: (B, n_feat)
    Built from Re Tr of closed loops -> invariant by construction.
    """
    B, D = links.shape[0], links.shape[1]
    feats = []

    def shift(x, mu, n=1):
        return torch.roll(x, shifts=-n, dims=2 + mu)

    def dag(x):
        return x.conj().transpose(-1, -2)

    def tr_re(x):
        return torch.diagonal(x, dim1=-2, dim2=-2 + 0).real if False else \
            torch.diagonal(x, dim1=-2, dim2=-1).real.sum(-1) / 3.0

    for mu in range(D):
        for nu in range(mu + 1, D):
            Umu = links[:, mu]; Unu = links[:, nu]
            P = (Umu @ shift(Unu, mu) @ dag(shift(Umu, nu)) @ dag(Unu))
            t = tr_re(P)                                   # (B,L,L,L,L)
            feats += [t.mean(dim=(1, 2, 3, 4)), t.std(dim=(1, 2, 3, 4))]
            # 1x2 rectangular loop
            R = (Umu @ Umu @ shift(Unu, mu, 2)
                 @ dag(shift(Umu, nu)) @ dag(shift(Umu, nu)) @ dag(Unu))
            feats.append(tr_re(R).mean(dim=(1, 2, 3, 4)))
            # 2x2 loop
            S = (Umu @ shift(Umu, mu) @ shift(Unu, mu, 2)
                 @ dag(shift(Umu, nu, 2)) @ dag(shift(Umu, nu)) @ dag(Unu))
            feats.append(tr_re(S).mean(dim=(1, 2, 3, 4)))
    # Polyakov loops per direction
    for mu in range(D):
        L = links.shape[2 + mu]
        prod = links[:, mu]
        for t in range(1, L):
            prod = prod @ torch.roll(links[:, mu], shifts=-t, dims=2 + mu)
        feats.append(tr_re(prod).mean(dim=(1, 2, 3, 4)))
    return torch.stack(feats, dim=-1).float()


class GaugeInvariantNet(nn.Module):
    """
    Predicts gauge-invariant observables from gauge-invariant loop features.
    Input features are Wilson-loop traces -> exactly gauge invariant.
    """
    def __init__(self, cfg: LGConfig, n_feat: int, n_out: int = 3):
        super().__init__()
        layers = []
        d = n_feat
        for _ in range(cfg.n_layers):
            layers += [nn.Linear(d, cfg.hidden), nn.SiLU(), nn.LayerNorm(cfg.hidden)]
            d = cfg.hidden
        layers += [nn.Linear(d, n_out)]
        self.net = nn.Sequential(*layers)
        self.register_buffer("ym", torch.zeros(n_out))
        self.register_buffer("ys", torch.ones(n_out))

    def set_norm(self, m, s):
        self.ym.copy_(torch.as_tensor(m)); self.ys.copy_(torch.as_tensor(s).clamp(min=1e-6))

    def forward(self, links: Tensor) -> Tensor:
        with torch.autocast(device_type=links.device.type, enabled=False):
            f = torch_plaquette_features(links.to(torch.complex64))
        return self.net(f) * self.ys + self.ym


def load_lg_dataset(path: Path):
    files = sorted(path.glob("cfg_*.npz"))
    if not files:
        return None, None
    items = []
    for f in files:
        d = np.load(f)
        items.append((d["links"],
                      np.array([d["plaquette"], d["plaq_flowed"], d["topo_flowed"]],
                               dtype=np.float32)))
    return items, files


def cmd_lg_train(args, cfg: LGConfig):
    if not HAS_TORCH:
        log.error("PyTorch required"); return
    dev, tag, rank, world = setup_ddp()
    seed_all(cfg.seed)
    items, files = load_lg_dataset(Path(args.data))
    if not items or len(items) < 4:
        log.error("Not enough configs — run lg-generate first"); return
    L = items[0][0].shape[1]
    D = items[0][0].shape[0]
    rng = np.random.default_rng(cfg.seed)
    idx = rng.permutation(len(items))
    nval = max(1, len(items) // 5)
    val = [items[i] for i in idx[:nval]]
    trn = [items[i] for i in idx[nval:]]

    def to_links(arr, device):
        t = torch.from_numpy(np.asarray(arr)).to(device)
        return t.reshape(D, L, L, L, L, 3, 3).unsqueeze(0)

    with torch.no_grad():
        probe = torch_plaquette_features(to_links(trn[0][0], dev))
        n_feat = probe.shape[-1]
    Y = np.stack([b[1] for b in trn])
    model = GaugeInvariantNet(cfg, n_feat).to(dev)
    model.set_norm(Y.mean(0), Y.std(0))
    if is_main():
        log.info(f"[lg-train] train={len(trn)} val={len(val)} "
                 f"L={L} D={D} invariant_features={n_feat}")
    if is_dist():
        model = DDP(model, device_ids=[dev.index] if dev.type == "cuda" else None)
    raw = model.module if isinstance(model, DDP) else model
    opt = torch.optim.AdamW(raw.parameters(), lr=cfg.lr, weight_decay=1e-5)
    sch = torch.optim.lr_scheduler.CosineAnnealingLR(opt, T_max=cfg.epochs)

    for ep in range(cfg.epochs):
        model.train()
        order = rng.permutation(len(trn))
        tot, nb = 0.0, 0
        for s in range(0, len(order), cfg.batch_size):
            batch = [trn[i] for i in order[s:s + cfg.batch_size]]
            links = torch.cat([to_links(b[0], dev) for b in batch], 0)
            y = torch.from_numpy(np.stack([b[1] for b in batch])).to(dev)
            opt.zero_grad(set_to_none=True)
            pred = model(links)
            loss = F.mse_loss(pred, y)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(raw.parameters(), 1.0)
            opt.step()
            tot += float(loss.detach()); nb += 1
        sch.step()
        if (ep + 1) % max(1, cfg.epochs // 20) == 0 or ep == cfg.epochs - 1:
            model.eval(); errs = []
            with torch.no_grad():
                for b in val:
                    p = raw(to_links(b[0], dev))[0].cpu().numpy()
                    errs.append(np.abs(p - b[1]))
            e = np.array(errs).mean(0)
            if is_main():
                log.info(f"ep {ep+1:4d} | train {tot/max(nb,1):.6f} | "
                         f"val MAE plaq={e[0]:.5f} plaq_flow={e[1]:.5f} Q={e[2]:.4f}")
    if is_main():
        Path(args.ckpt).parent.mkdir(parents=True, exist_ok=True)
        torch.save({"model": raw.state_dict(), "config": asdict(cfg),
                    "n_feat": n_feat}, args.ckpt)
        log.info(f"[lg-train] saved -> {args.ckpt}")
        log.info("HONEST: pure-gauge SU(3), quenched. No fermions, no continuum limit.")
    cleanup_ddp()


