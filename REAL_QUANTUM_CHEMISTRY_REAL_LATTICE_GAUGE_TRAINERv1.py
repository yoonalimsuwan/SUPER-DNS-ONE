class ACSF:
    """
    Atom-Centered Symmetry Functions.  Behler & Parrinello, PRL 98, 146401 (2007).
    Differentiable in torch -> forces by autograd.
    """
    def __init__(self, cfg: QCConfig, elements: List[str]):
        self.cfg = cfg
        self.elements = sorted(set(elements))
        self.eidx = {e: i for i, e in enumerate(self.elements)}
        self.ne = len(self.elements)

    @property
    def n_features(self) -> int:
        c = self.cfg
        n_rad = len(c.acsf_etas) * len(c.acsf_rs) * self.ne
        n_ang = (len(c.acsf_lambdas) * len(c.acsf_zetas) * self.ne * (self.ne + 1) // 2
                 if c.acsf_use_angular else 0)
        return n_rad + n_ang

    def cutoff(self, r):
        rc = self.cfg.acsf_rc
        return 0.5 * (torch.cos(math.pi * r / rc) + 1.0) * (r < rc).float()

    def __call__(self, Z: Tensor, R: Tensor, mask: Tensor) -> Tensor:
        """
        Z: (B,N) long, R: (B,N,3) float (requires_grad for forces), mask: (B,N)
        returns G: (B,N,n_features)
        """
        B, N = Z.shape
        c = self.cfg
        dev = R.device
        diff = R.unsqueeze(2) - R.unsqueeze(1)              # (B,N,N,3)
        r = torch.sqrt((diff * diff).sum(-1) + 1e-12)       # (B,N,N)
        eye = torch.eye(N, device=dev).unsqueeze(0)
        r = r + eye * 1e6
        pair_mask = mask.unsqueeze(1) * mask.unsqueeze(2)
        fc = self.cutoff(r) * pair_mask
        Zj = Z.unsqueeze(1).expand(B, N, N)
        onehot_j = F.one_hot(Zj, self.ne).float()           # (B,N,N,ne)

        feats = []
        for eta in c.acsf_etas:
            for rs in c.acsf_rs:
                g = torch.exp(-eta * (r - rs) ** 2) * fc    # (B,N,N)
                feats.append(torch.einsum("bijk,bijl->bik", g.unsqueeze(-1), onehot_j)
                             if False else (g.unsqueeze(-1) * onehot_j).sum(2))
        if c.acsf_use_angular:
            # angular G4/G5 (compact form)
            for lam in c.acsf_lambdas:
                for zeta in c.acsf_zetas:
                    cos_t = (diff.unsqueeze(2) * diff.unsqueeze(1)).sum(-1) / (
                        r.unsqueeze(2) * r.unsqueeze(1) + 1e-12)
                    cos_t = torch.clamp(cos_t, -1.0, 1.0)
                    ang = (1.0 + lam * cos_t).clamp(min=1e-8) ** zeta
                    rjk = r.unsqueeze(1)
                    rik = r.unsqueeze(2)
                    exp_t = torch.exp(-c.acsf_eta_ang *
                                      (r.unsqueeze(2) ** 2 + rjk ** 2 + rik ** 2))
                    f3 = fc.unsqueeze(2) * fc.unsqueeze(1) * self.cutoff(rjk)
                    base = 2.0 ** (1.0 - zeta) * ang * exp_t * f3
                    base = base * (pair_mask.unsqueeze(2) * pair_mask.unsqueeze(1))
                    feats.append(base.sum(dim=(2, 3)).unsqueeze(-1)
                                 .expand(-1, -1, self.ne).reshape(B, N, self.ne))
        G = torch.cat(feats, dim=-1)
        return G * mask.unsqueeze(-1)


class NeuralPotential(nn.Module):
    """
    HDNNP: shared element-conditioned MLP -> atomic energies -> sum.
    Forces = -dE/dR by autograd (exact, not finite difference).
    """
    def __init__(self, cfg: QCConfig, elements: List[str]):
        super().__init__()
        self.cfg = cfg
        self.acsf = ACSF(cfg, elements)
        self.elements = self.acsf.elements
        self.ne = self.acsf.ne
        nf = self.acsf.n_features + self.ne
        layers = []
        d = nf
        for _ in range(cfg.n_layers):
            layers += [nn.Linear(d, cfg.hidden), nn.SiLU()]
            d = cfg.hidden
        layers += [nn.Linear(d, 1)]
        self.net = nn.Sequential(*layers)
        # per-element energy offsets (linear reference)
        self.e_shift = nn.Parameter(torch.zeros(self.ne))
        self.register_buffer("e_mean", torch.zeros(1))
        self.register_buffer("e_std", torch.ones(1))

    def set_norm(self, mean: float, std: float):
        self.e_mean.fill_(mean); self.e_std.fill_(max(std, 1e-6))

    def forward(self, Z, R, mask, want_forces: bool = True):
        if want_forces and not R.requires_grad:
            R = R.detach().requires_grad_(True)
        G = self.acsf(Z, R, mask)
        oh = F.one_hot(Z, self.ne).float()
        x = torch.cat([G, oh], dim=-1)
        e_atom = self.net(x).squeeze(-1)                    # normalized units
        e_atom = e_atom * self.e_std + self.e_shift[Z]
        e_atom = e_atom * mask
        E = e_atom.sum(-1)
        forces = None
        if want_forces:
            g = torch.autograd.grad(E.sum(), R, create_graph=self.training,
                                    retain_graph=True)[0]
            forces = -g
        return {"energy": E, "forces": forces, "atomic_energy": e_atom}


def load_qc_dataset(path: Path, cfg: QCConfig):
    blob = json.load(open(path))
    data = blob["data"]
    elements = sorted({s for r in data for s in r["symbols"]})
    eidx = {e: i for i, e in enumerate(elements)}
    items = []
    for r in data:
        Z = np.array([eidx[s] for s in r["symbols"]], dtype=np.int64)
        R = np.array(r["coords"], dtype=np.float32)
        E = float(r["ref"]["e_ref"])
        Frc = np.array(r["ref"].get("forces", np.zeros_like(R)), dtype=np.float32)
        items.append((Z, R, E, Frc))
    return items, elements


def collate_qc(batch, device):
    nmax = max(len(b[0]) for b in batch)
    B = len(batch)
    Z = torch.zeros(B, nmax, dtype=torch.long)
    R = torch.zeros(B, nmax, 3)
    M = torch.zeros(B, nmax)
    E = torch.zeros(B)
    Fr = torch.zeros(B, nmax, 3)
    for i, (z, r, e, f) in enumerate(batch):
        n = len(z)
        Z[i, :n] = torch.from_numpy(z)
        R[i, :n] = torch.from_numpy(r)
        M[i, :n] = 1.0
        E[i] = e
        Fr[i, :n] = torch.from_numpy(f)
    return (Z.to(device), R.to(device), M.to(device),
            E.to(device), Fr.to(device))


def subsample_ci(x: np.ndarray, conf: float = 0.95, block: int = 16) -> Dict[str, float]:
    """Politis-Romano subsampling CI. Honest error bars, no distribution assumed."""
    n = len(x)
    if n < 8:
        m = float(np.mean(x)) if n else 0.0
        return {"mean": m, "lo": m, "hi": m, "n": n}
    b = min(block, n // 4)
    theta = float(np.mean(x))
    subs = np.array([np.mean(x[j:j + b]) for j in range(n - b + 1)])
    scaled = math.sqrt(b) * (subs - theta)
    a = 1 - conf
    lo = theta - float(np.percentile(scaled, 100 * (1 - a / 2))) / math.sqrt(n)
    hi = theta - float(np.percentile(scaled, 100 * (a / 2))) / math.sqrt(n)
    return {"mean": theta, "lo": lo, "hi": hi, "n": n}


def cmd_qc_train(args, cfg: QCConfig):
    if not HAS_TORCH:
        log.error("PyTorch required"); return
    dev, tag, rank, world = setup_ddp()
    seed_all(cfg.seed)
    cfg.epochs = args.epochs or cfg.epochs
    items, elements = load_qc_dataset(Path(args.data) / "labeled.json", cfg)
    if len(items) < 4:
        log.error("Not enough labeled data — run qc-label first"); return
    rng = np.random.default_rng(cfg.seed)
    idx = rng.permutation(len(items))
    nval = max(1, int(len(items) * cfg.val_frac))
    val = [items[i] for i in idx[:nval]]
    trn = [items[i] for i in idx[nval:]]

    # per-atom energy normalization (linear reference removal)
    e_per_atom = np.array([b[2] / len(b[0]) for b in trn])
    model = NeuralPotential(cfg, elements).to(dev)
    model.set_norm(float(e_per_atom.mean()), float(e_per_atom.std()))
    if is_main():
        log.info(f"[qc-train] train={len(trn)} val={len(val)} elements={elements} "
                 f"ACSF features={model.acsf.n_features}")
        log.info(f"[qc-train] params={sum(p.numel() for p in model.parameters()):,}")
    if is_dist():
        model = DDP(model, device_ids=[dev.index] if dev.type == "cuda" else None,
                    find_unused_parameters=False)
    raw = model.module if isinstance(model, DDP) else model

    opt = torch.optim.AdamW(raw.parameters(), lr=cfg.lr,
                            weight_decay=cfg.weight_decay)
    sch = torch.optim.lr_scheduler.CosineAnnealingLR(opt, T_max=cfg.epochs)
    amp_dt = torch.bfloat16 if cfg.amp_dtype == "bf16" else torch.float16
    use_amp = cfg.amp_dtype != "fp32" and dev.type == "cuda"
    scaler = torch.amp.GradScaler(enabled=(use_amp and amp_dt == torch.float16))

    best = float("inf")
    for ep in range(cfg.epochs):
        model.train()
        order = rng.permutation(len(trn))
        tot, nb = 0.0, 0
        for s in range(0, len(order), cfg.batch_size):
            batch = [trn[i] for i in order[s:s + cfg.batch_size]]
            Z, R, M, E, Fr = collate_qc(batch, dev)
            opt.zero_grad(set_to_none=True)
            with amp_ctx(dev, tag, amp_dt, use_amp):
                out = model(Z, R, M, want_forces=True)
                nat = M.sum(-1)
                e_err = (out["energy"] - E) / nat          # per-atom
                loss_e = (e_err ** 2).mean()
                loss_f = torch.tensor(0.0, device=dev)
                if out["forces"] is not None and cfg.force_weight > 0:
                    fm = M.unsqueeze(-1)
                    loss_f = (((out["forces"] - Fr) * fm) ** 2).sum() / (fm.sum() * 3)
                loss = loss_e + cfg.force_weight * loss_f
            scaler.scale(loss).backward()
            scaler.unscale_(opt)
            torch.nn.utils.clip_grad_norm_(raw.parameters(), cfg.grad_clip)
            scaler.step(opt); scaler.update()
            tot += float(loss.detach()); nb += 1
        sch.step()

        if (ep + 1) % max(1, cfg.epochs // 20) == 0 or ep == cfg.epochs - 1:
            model.eval()
            errs = []
            with torch.no_grad():
                for s in range(0, len(val), cfg.batch_size):
                    batch = val[s:s + cfg.batch_size]
                    Z, R, M, E, Fr = collate_qc(batch, dev)
                    o = raw(Z, R, M, want_forces=False)
                    errs.extend(((o["energy"] - E) / M.sum(-1)).cpu().numpy()
                                * HARTREE_TO_KCAL)
            errs = np.abs(np.array(errs))
            ci = subsample_ci(errs)
            if is_main():
                log.info(f"ep {ep+1:4d} | train {tot/max(nb,1):.5f} | "
                         f"val MAE {ci['mean']:.3f} kcal/mol/atom "
                         f"[{ci['lo']:.3f}, {ci['hi']:.3f}]")
            if ci["mean"] < best:
                best = ci["mean"]
                if is_main():
                    Path(args.ckpt).parent.mkdir(parents=True, exist_ok=True)
                    torch.save({"model": raw.state_dict(),
                                "elements": elements,
                                "config": asdict(cfg),
                                "val_mae_kcal_per_atom": best}, args.ckpt)
    if is_main():
        log.info(f"[qc-train] best val MAE = {best:.3f} kcal/mol/atom")
        log.info("HONEST: chemical accuracy = 1 kcal/mol on TOTAL energy, "
                 "requires far more data + independent test set.")
    cleanup_ddp()


