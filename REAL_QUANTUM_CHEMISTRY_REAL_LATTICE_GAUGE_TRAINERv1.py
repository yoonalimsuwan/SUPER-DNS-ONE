class SU3Lattice:
    """
    Pure-gauge SU(3) Wilson lattice.
      S = -(beta/3) sum_plaquette Re Tr U_plaq        [Wilson 1974]
    Updates: Cabibbo-Marinari SU(2) subgroups [Cabibbo-Marinari 1982]
             Metropolis accept/reject (detailed balance)
             + microcanonical overrelaxation
    NOTE: Metropolis is used instead of Kennedy-Pendleton heatbath for
          correctness transparency. Heatbath is more efficient; this is
          a documented, valid alternative.
    """
    SUBGROUPS = [(0, 1), (0, 2), (1, 2)]

    def __init__(self, cfg: LGConfig):
        self.cfg = cfg
        self.L = cfg.lsize
        self.D = cfg.ndim
        self.N = self.L ** self.D
        self.rng = np.random.default_rng(cfg.seed)
        self.links = self.cold_start()
        self.coords = self._coords()
        self.acc = 0; self.prop = 0

    def _coords(self) -> np.ndarray:
        grids = np.meshgrid(*[np.arange(self.L) for _ in range(self.D)], indexing="ij")
        return np.stack([g.reshape(-1) for g in grids], axis=-1)   # (N, D)

    def idx(self, c: np.ndarray) -> np.ndarray:
        c = np.mod(c, self.L)
        out = np.zeros(c.shape[:-1], dtype=np.int64)
        for d in range(self.D):
            out = out * self.L + c[..., d]
        return out

    def cold_start(self) -> np.ndarray:
        U = np.zeros((self.D, self.N, 3, 3), dtype=np.complex128)
        U[:] = np.eye(3, dtype=np.complex128)
        return U

    def hot_start(self):
        self.links = self.random_su3((self.D, self.N))

    def random_su3(self, shape) -> np.ndarray:
        """Haar-random SU(3) via QR of complex Ginibre (Mezzadri 2007)."""
        n = int(np.prod(shape))
        A = (self.rng.normal(size=(n, 3, 3)) + 1j * self.rng.normal(size=(n, 3, 3)))
        Q, R = np.linalg.qr(A)
        ph = np.diagonal(R, axis1=-2, axis2=-1)
        ph = ph / np.abs(ph)
        Q = Q * ph[..., None, :]
        det = np.linalg.det(Q)
        Q[:, 0, :] /= det[:, None]
        return Q.reshape(*shape, 3, 3)

    @staticmethod
    def project_su3(M: np.ndarray) -> np.ndarray:
        """Polar projection to SU(3)."""
        U, _, Vh = np.linalg.svd(M)
        X = U @ Vh
        det = np.linalg.det(X)
        X = X / det[..., None, None] ** (1.0 / 3.0)
        return X

    def staples(self, mu: int) -> np.ndarray:
        """Sum of staples for direction mu. Shape (N,3,3)."""
        c = self.coords
        V = np.zeros((self.N, 3, 3), dtype=np.complex128)
        Umu = self.links[mu]
        for nu in range(self.D):
            if nu == mu:
                continue
            cmu = c.copy(); cmu[:, mu] += 1
            cnu = c.copy(); cnu[:, nu] += 1
            cmu_back = cnu.copy(); cmu_back[:, mu] -= 1
            i_mu = self.idx(cmu); i_nu = self.idx(cnu); i_b = self.idx(cmu_back)
            Unu = self.links[nu]
            # forward staple
            V += Unu[i_mu] @ Umu[i_nu].conj().transpose(0, 2, 1) @ Unu[i_b].conj().transpose(0, 2, 1)
            # backward staple
            cmu2 = c.copy(); cmu2[:, mu] -= 1
            i_m2 = self.idx(cmu2)
            cnu2 = cmu2.copy(); cnu2[:, nu] += 1
            i_n2 = self.idx(cnu2)
            V += Unu[i_m2].conj().transpose(0, 2, 1) @ Umu[i_n2] @ Unu[i_m2]
        return V

    def plaquette_avg(self) -> float:
        """Average plaquette (1/3) Re Tr U_plaq over all oriented plaquettes."""
        c = self.coords
        tot, cnt = 0.0, 0
        for mu in range(self.D):
            cmu = c.copy(); cmu[:, mu] += 1
            i_mu = self.idx(cmu)
            for nu in range(mu + 1, self.D):
                cnu = c.copy(); cnu[:, nu] += 1
                i_nu = self.idx(cnu)
                P = (self.links[mu] @ self.links[nu][i_mu]
                     @ self.links[mu][i_nu].conj().transpose(0, 2, 1)
                     @ self.links[nu].conj().transpose(0, 2, 1))
                tr = np.trace(P, axis1=-2, axis2=-1).real / 3.0
                tot += float(tr.mean()); cnt += 1
        return tot / max(cnt, 1)

    def action(self) -> float:
        nplaq = self.D * (self.D - 1) // 2
        return self.cfg.beta * nplaq * self.N * (1.0 - self.plaquette_avg())

    def polyakov(self) -> complex:
        """Traced Polyakov loop along direction 0."""
        c = self.coords
        mask = np.ones(self.N, dtype=bool)
        for d in range(1, self.D):
            mask &= (c[:, d] == 0)
        line = c[mask]
        prod = np.tile(np.eye(3, dtype=np.complex128), (len(line), 1, 1))
        for t in range(self.L):
            cc = line.copy(); cc[:, 0] = t
            prod = prod @ self.links[0][self.idx(cc)]
        return complex(np.trace(prod, axis1=-2, axis2=-1).mean() / 3.0)

    def clover_topo_charge(self) -> float:
        """Clover-definition topological charge Q = 1/(32 pi^2) sum eps Tr(FF)."""
        c = self.coords
        F = np.zeros((self.D, self.D, self.N, 3, 3), dtype=np.complex128)
        for mu in range(self.D):
            for nu in range(mu + 1, self.D):
                Q = self._clover_leaf(mu, nu, c)
                F[mu, nu] = Q
                F[nu, mu] = -Q
        eps = np.zeros((self.D,) * 4)
        import itertools
        for perm in itertools.permutations(range(4)):
            inv = sum(1 for i in range(4) for j in range(i + 1, 4) if perm[i] > perm[j])
            eps[perm] = (-1.0) ** inv
        acc = 0.0
        for mu in range(self.D):
            for nu in range(self.D):
                for rho in range(self.D):
                    for sig in range(self.D):
                        if eps[mu, nu, rho, sig] == 0:
                            continue
                        prod = F[mu, nu] @ F[rho, sig]
                        tr = np.trace(prod, axis1=-2, axis2=-1).real
                        acc += eps[mu, nu, rho, sig] * float(tr.sum())
        return acc / (32.0 * math.pi ** 2)

    def _clover_leaf(self, mu, nu, c):
        cmu = c.copy(); cmu[:, mu] += 1
        cnu = c.copy(); cnu[:, nu] += 1
        cm1 = c.copy(); cm1[:, mu] -= 1
        cn1 = c.copy(); cn1[:, nu] -= 1
        i0 = np.arange(self.N)
        imu, inu = self.idx(cmu), self.idx(cnu)
        im1, in1 = self.idx(cm1), self.idx(cn1)
        Um, Un = self.links[mu], self.links[nu]
        Umd, Und = Um.conj().transpose(0, 2, 1), Un.conj().transpose(0, 2, 1)

        def plaq(a, b, start):
            ca = start.copy(); ca[:, a] += 1
            cb = start.copy(); cb[:, b] += 1
            return (self.links[a][self.idx(start)] @ self.links[b][self.idx(ca)]
                    @ self.links[a][self.idx(cb)].conj().transpose(0, 2, 1)
                    @ self.links[b][self.idx(start)].conj().transpose(0, 2, 1))

        p1 = plaq(mu, nu, c)
        cm = c.copy(); cm[:, nu] -= 1
        p2 = plaq(mu, nu, cm)
        cmm = cm1.copy(); cmm[:, nu] -= 1
        p3 = plaq(mu, nu, cmm)
        p4 = plaq(mu, nu, cm1)
        C = p1 + p2 + p3 + p4
        A = C - C.conj().transpose(0, 2, 1)
        A = A - np.trace(A, axis1=-2, axis2=-1)[..., None, None] / 3.0
        return A / 8.0

    # ---------------- Monte Carlo updates ----------------
    def _su2_embed(self, a: np.ndarray, ij: Tuple[int, int]) -> np.ndarray:
        """Embed 2x2 SU(2) into 3x3."""
        n = a.shape[0]
        M = np.tile(np.eye(3, dtype=np.complex128), (n, 1, 1))
        i, j = ij
        M[:, i, i] = a[:, 0, 0]; M[:, i, j] = a[:, 0, 1]
        M[:, j, i] = a[:, 1, 0]; M[:, j, j] = a[:, 1, 1]
        return M

    def _random_su2(self, n: int, eps: float) -> np.ndarray:
        v = self.rng.normal(size=(n, 4))
        v /= np.linalg.norm(v, axis=-1, keepdims=True)
        v[:, 0] = 1.0 - eps + eps * v[:, 0]
        v /= np.linalg.norm(v, axis=-1, keepdims=True)
        a0, a1, a2, a3 = v[:, 0], v[:, 1], v[:, 2], v[:, 3]
        a = np.empty((n, 2, 2), dtype=np.complex128)
        a[:, 0, 0] = a0 + 1j * a3; a[:, 0, 1] = a2 + 1j * a1
        a[:, 1, 0] = -a2 + 1j * a1; a[:, 1, 1] = a0 - 1j * a3
        return a

    def _su2_project(self, w: np.ndarray) -> np.ndarray:
        """Project 2x2 complex block to SU(2)."""
        a0 = (w[:, 0, 0] + np.conj(w[:, 1, 1])) / 2
        a3 = (w[:, 0, 0] - np.conj(w[:, 1, 1])) / (2j)
        a2 = (w[:, 0, 1] - np.conj(w[:, 1, 0])) / 2
        a1 = (w[:, 0, 1] + np.conj(w[:, 1, 0])) / (2j)
        nrm = np.sqrt(np.abs(a0) ** 2 + np.abs(a1) ** 2 +
                      np.abs(a2) ** 2 + np.abs(a3) ** 2) + 1e-14
        a0, a1, a2, a3 = a0 / nrm, a1 / nrm, a2 / nrm, a3 / nrm
        a = np.empty_like(w)
        a[:, 0, 0] = a0 + 1j * a3; a[:, 0, 1] = a2 + 1j * a1
        a[:, 1, 0] = -a2 + 1j * a1; a[:, 1, 1] = a0 - 1j * a3
        return a

    def metropolis_sweep(self):
        """One Metropolis sweep over all links, all SU(2) subgroups."""
        beta3 = self.cfg.beta / 3.0
        for mu in range(self.D):
            V = self.staples(mu)
            U = self.links[mu]
            for ij in self.SUBGROUPS:
                i, j = ij
                for _ in range(self.cfg.metro_hits):
                    n = self.N
                    a = self._random_su2(n, self.cfg.metro_eps)
                    R = self._su2_embed(a, ij)
                    Unew = R @ U
                    dS = -beta3 * np.trace((Unew - U) @ V, axis1=-2, axis2=-1).real
                    accept = self.rng.random(n) < np.exp(-np.clip(dS, -50, 50))
                    U[accept] = Unew[accept]
                    self.acc += int(accept.sum()); self.prop += n
            self.links[mu] = self.project_su3(U)

    def overrelax_sweep(self):
        """Microcanonical overrelaxation (action-preserving, reduces autocorr)."""
        for mu in range(self.D):
            V = self.staples(mu)
            U = self.links[mu]
            for ij in self.SUBGROUPS:
                i, j = ij
                W = U @ V
                w = W[:, [i, j], :][:, :, [i, j]]
                k = self._su2_project(w)
                kd = k.conj().transpose(0, 2, 1)
                a_old = U[:, [i, j], :][:, :, [i, j]]
                a_new = kd @ a_old.conj().transpose(0, 2, 1) @ kd
                R = self._su2_embed(a_new @ a_old.conj().transpose(0, 2, 1), ij)
                U = R @ U
            self.links[mu] = self.project_su3(U)

    def sweep(self):
        self.metropolis_sweep()
        for _ in range(self.cfg.overrelax_steps):
            self.overrelax_sweep()

    def wilson_flow(self, nsteps: int, eps: float):
        """
        Wilson gradient flow (Euler discretization + reunitarization).
        Lüscher, JHEP 08 (2010) 071.  Euler is O(eps); RK3 is better.
        """
        for _ in range(nsteps):
            new = self.links.copy()
            for mu in range(self.D):
                V = self.staples(mu)
                U = self.links[mu]
                W = U @ V
                A = W - W.conj().transpose(0, 2, 1)
                A = A - np.trace(A, axis1=-2, axis2=-1)[..., None, None] / 3.0
                new[mu] = self.project_su3(U - eps * (self.cfg.beta / 6.0) * A @ U)
            self.links = new

    def acceptance(self) -> float:
        return self.acc / max(self.prop, 1)


