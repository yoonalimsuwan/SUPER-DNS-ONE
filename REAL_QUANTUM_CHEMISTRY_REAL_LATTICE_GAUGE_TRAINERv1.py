def fetch_pubchem_3d(cid: int, timeout: int = 30) -> Optional[List[Tuple[str, float, float, float]]]:
    """Fetch a REAL deposited 3D conformer from PubChem PUG-REST."""
    if not (HAS_REQUESTS and HAS_RDKIT):
        return None
    url = ("https://pubchem.ncbi.nlm.nih.gov/rest/pug/compound/cid/"
           f"{cid}/record/SDF/?record_type=3d&response_type=save")
    try:
        r = requests.get(url, timeout=timeout)
        if r.status_code != 200 or not r.text.strip():
            return None
        mol = Chem.MolFromMolBlock(r.text, removeHs=False)
        if mol is None:
            return None
        mol = Chem.AddHs(mol, addCoords=True)
        if mol.GetNumConformers() == 0:
            AllChem.EmbedMolecule(mol, randomSeed=42)
        conf = mol.GetConformer()
        out = []
        for a in mol.GetAtoms():
            p = conf.GetAtomPosition(a.GetIdx())
            out.append((a.GetSymbol(), float(p.x), float(p.y), float(p.z)))
        return out
    except Exception as e:
        log.warning(f"PubChem CID {cid} failed: {e}")
        return None


def rdkit_conformers(geom: List[Tuple[str, float, float, float]],
                     n: int, seed: int = 42) -> List[np.ndarray]:
    """Generate additional REAL conformers with ETKDG (文献: Riniker & Landrum 2015)."""
    if not HAS_RDKIT or n <= 1:
        return [np.array([[g[1], g[2], g[3]] for g in geom])]
    try:
        xyz = f"{len(geom)}\n\n" + "\n".join(
            f"{s} {x:.6f} {y:.6f} {z:.6f}" for s, x, y, z in geom)
        mol = Chem.MolFromXYZBlock(xyz)
        if mol is None:
            return [np.array([[g[1], g[2], g[3]] for g in geom])]
        from rdkit.Chem import rdDetermineBonds
        rdDetermineBonds.DetermineConnectivity(mol)
        params = AllChem.ETKDGv3()
        params.randomSeed = seed
        ids = AllChem.EmbedMultipleConfs(mol, numConfs=n, params=params)
        if len(ids) == 0:
            return [np.array([[g[1], g[2], g[3]] for g in geom])]
        return [np.array(mol.GetConformer(i).GetPositions()) for i in ids]
    except Exception:
        return [np.array([[g[1], g[2], g[3]] for g in geom])]


def pyscf_reference(symbols: List[str],
                    coords_ang: np.ndarray,
                    cfg: QCConfig) -> Optional[Dict[str, Any]]:
    """
    Compute REAL ab initio reference with PySCF.
    This is the ground truth. Integrals come from libcint, not from a network.
    """
    if not HAS_PYSCF:
        return None
    atom = [[s, tuple(map(float, c))] for s, c in zip(symbols, coords_ang)]
    try:
        mol = gto.M(atom=atom, basis=cfg.basis, unit="Angstrom",
                    verbose=0, max_memory=4000)
        mol.build()
    except Exception as e:
        log.warning(f"PySCF mol build failed: {e}")
        return None

    try:
        mf = scf.RHF(mol)
        mf.conv_tol = cfg.scf_conv_tol
        mf.max_cycle = cfg.max_cycle
        e_hf = float(mf.kernel())
        if not mf.converged:
            log.warning("SCF did not converge — skipping geometry")
            return None

        out: Dict[str, Any] = {"e_hf": e_hf, "n_elec": mol.nelectron,
                               "n_orb": mol.nao_nr()}
        e_ref = e_hf
        mo = mf.mo_coeff

        if cfg.method in ("mp2", "ccsd", "ccsd_t"):
            m2 = mp.MP2(mf).run()
            out["e_mp2"] = float(m2.e_tot)
            e_ref = out["e_mp2"]

        if cfg.method in ("ccsd", "ccsd_t"):
            mycc = cc.CCSD(mf).run()
            out["e_ccsd"] = float(mycc.e_tot)
            e_ref = out["e_ccsd"]
            if cfg.method == "ccsd_t":
                et = mycc.ccsd_t()
                out["e_ccsd_t"] = float(mycc.e_tot + et)
                e_ref = out["e_ccsd_t"]

        if cfg.method == "casci":
            ncas = min(cfg.casci_ncas, mol.nao_nr())
            nel = min(cfg.casci_nelecas, mol.nelectron)
            if nel % 2 != ncas % 2:
                nel = max(2, nel - 1)
            mc = mcscf.CASCI(mf, ncas, nel)
            mc.verbose = 0
            mc.run(mo)
            out["e_casci"] = float(mc.e_tot)
            e_ref = out["e_casci"]

        out["e_ref"] = e_ref

        # analytic HF nuclear gradients (real forces)
        if cfg.compute_forces:
            try:
                g = mf.nuc_grad_method().kernel()   # Hartree/Bohr
                out["forces"] = (-np.asarray(g) / BOHR_TO_ANG).astype(np.float32)
            except Exception:
                out["forces"] = np.zeros_like(coords_ang, dtype=np.float32)

        eo = mf.mo_energy
        nocc = mol.nelectron // 2
        out["homo"] = float(eo[nocc - 1]) if nocc > 0 else 0.0
        out["lumo"] = float(eo[nocc]) if nocc < len(eo) else 0.0
        out["gap_ev"] = (out["lumo"] - out["homo"]) * HARTREE_TO_EV
        try:
            out["dipole"] = np.asarray(mf.dip_moment(unit="Debye", verbose=0),
                                       dtype=np.float32)
        except Exception:
            out["dipole"] = np.zeros(3, dtype=np.float32)
        return out
    except Exception as e:
        log.warning(f"PySCF calculation failed: {e}")
        return None


def cmd_qc_fetch(args, cfg: QCConfig):
    """Collect REAL geometries: PubChem 3D, else literature built-ins."""
    out = Path(args.out); out.mkdir(parents=True, exist_ok=True)
    records = []
    if HAS_REQUESTS and HAS_RDKIT:
        for cid in cfg.pubchem_cids:
            g = fetch_pubchem_3d(cid)
            if g is None:
                log.info(f"CID {cid}: no 3D record, skipping")
                continue
            syms = [x[0] for x in g]
            base = np.array([[x[1], x[2], x[3]] for x in g])
            confs = rdkit_conformers(g, cfg.n_conformers, cfg.seed)
            for ci, c in enumerate(confs):
                records.append({"name": f"cid{cid}_conf{ci}", "cid": cid,
                                "symbols": syms, "coords": c.tolist(),
                                "source": "pubchem_3d+ETKDG"})
            log.info(f"CID {cid}: {len(confs)} conformers")
            time.sleep(0.2)  # be polite to PubChem
    if not records:
        log.warning("PubChem unavailable — using literature built-in geometries")
        for name, g in BUILTIN_GEOMETRIES.items():
            syms = [x[0] for x in g]
            base = np.array([[x[1], x[2], x[3]] for x in g])
            confs = rdkit_conformers(g, cfg.n_conformers, cfg.seed)
            for ci, c in enumerate(confs):
                records.append({"name": f"{name}_conf{ci}", "cid": -1,
                                "symbols": syms, "coords": c.tolist(),
                                "source": "literature_builtin+ETKDG"})
    # displaced geometries so forces are non-trivial
    rng = np.random.default_rng(cfg.seed)
    aug = []
    for r in records:
        aug.append(r)
        c0 = np.array(r["coords"])
        for k in range(cfg.n_rattle):
            aug.append({**r, "name": r["name"] + f"_r{k}",
                        "coords": (c0 + rng.normal(0, cfg.rattle_sigma, c0.shape)).tolist(),
                        "source": r["source"] + "+rattle"})
    with open(out / "geometries.json", "w") as f:
        json.dump(aug, f)
    log.info(f"[qc-fetch] {len(aug)} geometries -> {out/'geometries.json'}")


def cmd_qc_label(args, cfg: QCConfig):
    """Run REAL PySCF on every geometry. This is the expensive, honest step."""
    if not HAS_PYSCF:
        log.error("PySCF not installed.  pip install pyscf")
        return
    cfg.basis = args.basis or cfg.basis
    cfg.method = args.method or cfg.method
    src = Path(args.src) / "geometries.json"
    if not src.exists():
        log.error(f"{src} missing — run qc-fetch first"); return
    records = json.load(open(src))
    out = Path(args.out); out.mkdir(parents=True, exist_ok=True)
    labeled, failed = [], 0
    t0 = time.time()
    for i, r in enumerate(records):
        ref = pyscf_reference(r["symbols"], np.array(r["coords"]), cfg)
        if ref is None:
            failed += 1; continue
        labeled.append({**r, "ref": {k: (v.tolist() if isinstance(v, np.ndarray) else v)
                                      for k, v in ref.items()}})
        if (i + 1) % 10 == 0 and is_main():
            log.info(f"[qc-label] {i+1}/{len(records)}  ok={len(labeled)} fail={failed} "
                     f"({time.time()-t0:.1f}s)")
    with open(out / "labeled.json", "w") as f:
        json.dump({"config": asdict(cfg), "data": labeled}, f)
    log.info(f"[qc-label] DONE  ok={len(labeled)}  fail={failed}  "
             f"basis={cfg.basis} method={cfg.method}  -> {out/'labeled.json'}")
    log.info("These are REAL ab initio labels. The model below learns them.")


