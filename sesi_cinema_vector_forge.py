@dataclass
class PSRConfig:
    lam: float = 6.0              # screening strength (Kazhdan)
    pad: int = 4                  # zero padding; REQUIRED for watertightness
    level: float = 0.5            # isosurface of the normalised indicator
    sharpness: float = 3.0        # indicator sigmoid sharpness
    min_pad: int = 1
    refuse_without_padding: bool = True


class DifferentiablePoissonReconstructor(nn.Module):
    """
    [C/D] Screened Poisson reconstruction, closed form in Fourier.

        minimise  int |grad chi - V|^2 + lam^2 chi^2
        =>        (-Lap + lam^2) chi = div V
        Fourier:  chi_hat = (i k . V_hat) / (k^2 + lam^2)

    torch.fft is autograd-exact, so there is NO unrolled solver and NO
    iteration-count hyper-parameter. This is the fully differentiable
    topology path (Marching Cubes connectivity is discrete).

    WATERTIGHT GUARANTEE [P-conditional]
      The indicator V is built from a PADDED field and chi is min-max
      normalised, so chi < level on the entire boundary of the periodic box.
      A regular isosurface of a continuous scalar field that does not meet
      the boundary of its domain is a closed 2-manifold: every edge of the
      dual grid carries an even number of incident surface polygons and no
      polygon touches the box. Hence dM = empty and the mesh is watertight.
      If `pad` is set to 0 the guarantee is VOID and, when
      `refuse_without_padding` is set, this class raises instead of
      silently returning an open mesh.
    """

    def __init__(self, cfg: Optional[PSRConfig] = None):
        super().__init__()
        self.cfg = cfg or PSRConfig()
        self.mc = MarchingCubesExtractor(level=self.cfg.level)

    @staticmethod
    def _wavenumbers(shape, device, dtype, dx: float) -> Tensor:
        ks = []
        for i, n in enumerate(shape):
            if i == len(shape) - 1:
                ks.append(torch.fft.rfftfreq(n, d=dx / (2 * math.pi),
                                             dtype=dtype, device=device))
            else:
                ks.append(torch.fft.fftfreq(n, d=dx / (2 * math.pi),
                                            dtype=dtype, device=device))
        return torch.meshgrid(*ks, indexing="ij")

    def indicator(self, u: Tensor, dx: float = 1.0) -> Tensor:
        """Smooth inside-indicator phi in [0,1] from the phase field."""
        return torch.sigmoid((u - self.mc.level) * self.cfg.sharpness / max(dx, 1e-9))

    def solve(self, phi: Tensor, dx: float = 1.0) -> Tensor:
        """Screened Poisson solve; returns chi normalised to [0,1]."""
        with _fp32_island(str(phi.device.type)):
            p = phi.float()
            # gradients of the indicator -> the target vector field V
            comps = [(torch.roll(p, -1, ax) - torch.roll(p, 1, ax)) / (2 * dx)
                     for ax in range(p.dim())]
            V = torch.stack(comps, dim=0)

            shape = p.shape
            kgrids = self._wavenumbers(shape, p.device, p.dtype, dx)
            k2 = sum(k ** 2 for k in kgrids)

            V_hat = torch.fft.rfftn(V, norm="ortho", dim=tuple(range(1, V.dim())))
            num = sum(1j * k.unsqueeze(0) * V_hat[i]
                      for i, k in enumerate(kgrids))
            denom = k2 + self.cfg.lam ** 2
            denom = torch.where(denom < 1e-12, torch.ones_like(denom), denom)
            chi_hat = num / denom
            chi = torch.fft.irfftn(chi_hat, s=shape, norm="ortho")

            # mean-zero from the solve; add the indicator mean back
            chi = chi + p.mean()

            # min-max normalise with DETACHED scalars -> gradient is exact
            lo = chi.min().detach()
            hi = chi.max().detach()
            span = (hi - lo).clamp_min(1e-12)
            return ((chi - lo) / span).to(phi.dtype)

    def reconstruct(self, u: Tensor, dx: float = 1.0,
                    verify_watertight: bool = True) -> Dict[str, Any]:
        """
        u: (X,Y,Z) phase field. Returns watertight mesh + PSR diagnostics.
        """
        pad = self.cfg.pad
        if pad <= 0 and self.cfg.refuse_without_padding:
            raise ValueError(
                "PSR watertight guarantee requires pad >= 1. Padding disabled "
                "would let the isosurface meet the periodic boundary and open "
                "the mesh. Set cfg.pad > 0, or set refuse_without_padding=False "
                "and accept an OPEN mesh.")

        # pad with values well OUTSIDE the surface so chi -> 0 on the boundary
        if pad > 0:
            lo_val = float(self.mc.level) - 4.0 / max(self.cfg.sharpness, 1e-9)
            u_pad = F.pad(u, (pad, pad) * u.dim(), mode="constant", value=lo_val)
        else:
            u_pad = u

        phi = self.indicator(u_pad, dx)
        chi = self.solve(phi, dx)

        mesh = self.mc.extract(chi, dx=dx)
        out = {
            "chi": chi,
            "phi": phi,
            "mesh": mesh,
            "pad": pad,
            "chi_boundary_max": float(chi.flatten()[: chi.shape[0]].max()) if pad == 0
                                 else float(max(
                                     chi[0].max(), chi[-1].max(),
                                     chi[:, 0].max(), chi[:, -1].max(),
                                     chi[:, :, 0].max(), chi[:, :, -1].max())),
            "level": self.cfg.level,
        }
        out["boundary_below_level"] = out["chi_boundary_max"] < self.cfg.level
        out["watertight_guarantee_holds"] = bool(
            pad > 0 and out["boundary_below_level"])

        if verify_watertight and mesh["n_faces"] > 0:
            eul = MarchingCubesExtractor.euler_characteristic(
                mesh["faces"], mesh["n_vertices"])
            out["euler"] = eul
            out["watertight_measured"] = bool(
                eul["watertight"] and eul["boundary_edges"] == 0)
            if not out["watertight_measured"]:
                logger.warning("PSR produced %d boundary edges; the guarantee "
                               "assumes a smooth chi. Increase cfg.lam or pad.",
                               eul["boundary_edges"])
        return out


