class BlendMode(str, Enum):
    NORMAL = "normal"
    MULTIPLY = "multiply"
    SCREEN = "screen"
    OVERLAY = "overlay"
    ADD = "add"
    SOFT_LIGHT = "soft_light"


@dataclass
class TextureLayer:
    name: str
    kind: str = "pfc"            # pfc | ch | thin_film | carpet_sigma | noise
    opacity: float = 0.5
    blend: BlendMode = BlendMode.NORMAL
    scale: float = 1.0
    steps: int = 12
    seed: int = 0
    triplanar: bool = True
    displacement_gain: float = 0.0


def _blend(a: Tensor, b: Tensor, mode: BlendMode) -> Tensor:
    if mode == BlendMode.MULTIPLY:
        return a * b
    if mode == BlendMode.SCREEN:
        return 1.0 - (1.0 - a) * (1.0 - b)
    if mode == BlendMode.OVERLAY:
        return torch.where(a < 0.5, 2 * a * b,
                           1 - 2 * (1 - a) * (1 - b))
    if mode == BlendMode.ADD:
        return (a + b).clamp(0, 1)
    if mode == BlendMode.SOFT_LIGHT:
        return (1 - 2 * b) * (a ** 2) + 2 * b * a
    return b


class ProceduralTextureStack(nn.Module):
    """
    [D] Layered procedural material, 3ds Max-style.

    Layers are generated by the EMBEDDED PFC / CH / thin-film solvers, so the
    material is a genuine physical phase field rather than a tiling bitmap:
      * PFC     -> crystalline grain, dendrites, lattice orientation
      * CH      -> spinodal decomposition, marble, two-phase blends
      * ThinFilm-> dewetting, crackle, oil-slick, droplet beading
      * carpet_sigma -> fractal-measure mottling at the calibrated d_f
    Triplanar projection removes UV seams on arbitrary meshes.
    """

    def __init__(self, ch_epsilon: float = 1.5, pfc_r: float = -0.5):
        super().__init__()
        cfg_pfc = CahnHilliardConfig(dx=1.0, epsilon=ch_epsilon, dt=1e-6,
                                     pfc_r=pfc_r, laplacian="conv3d",
                                     scheme="imex", dtype=torch.float32)
        cfg_ch = CahnHilliardConfig(dx=1.0, epsilon=ch_epsilon, dt=1e-5,
                                    laplacian="conv3d", scheme="imex",
                                    dtype=torch.float32)
        cfg_tf = CahnHilliardConfig(dx=1.0, epsilon=ch_epsilon, dt=1e-6,
                                    thin_film=True, surface_diffusion=True,
                                    kappa_s=0.01, laplacian="conv3d",
                                    scheme="explicit", dtype=torch.float32)
        self.pfc = PhaseFieldCrystal3D(cfg_pfc)
        self.ch = StructuralCahnHilliard3D(cfg_ch)
        self.thinfilm = ThinFilmStructuralCahnHilliard3D(cfg_tf)
        self.amr = CarpetAMRController()

    def _solver_for(self, kind: str) -> nn.Module:
        return {"pfc": self.pfc, "ch": self.ch,
                "thin_film": self.thinfilm}.get(kind, self.ch)

    def generate_layer(self, shape: Tuple[int, int, int], layer: TextureLayer,
                       sigma: Optional[Tensor] = None) -> Tensor:
        """Generate one layer as a field in ~[0,1]."""
        g = torch.Generator(device="cpu").manual_seed(layer.seed)
        dev = next(self.pfc.parameters()).device if any(
            True for _ in self.pfc.parameters()) else torch.device("cpu")
        if layer.kind == "carpet_sigma":
            s = self.amr.fractal_sigma(shape, 3, dev, torch.float32)
            s = s / s.max().clamp_min(1e-12)
            return s
        if layer.kind == "noise":
            return torch.rand(*shape, generator=g).to(dev)

        u = (torch.rand(*shape, generator=g, dtype=torch.float32) * 0.4 - 0.2).to(dev)
        if sigma is None:
            sigma = torch.ones_like(u)
        solver = self._solver_for(layer.kind)
        for _ in range(layer.steps):
            u = solver.step(u, sigma)
        u = u - u.mean()
        u = u / (u.std() + 1e-8)
        return (u * 0.5 + 0.5).clamp(0, 1)

    @staticmethod
    def triplanar(vol: Tensor, weights: Optional[Tensor] = None) -> Tensor:
        """
        [D] Triplanar projection: blend the three axis-aligned slices by
        surface normal. Removes UV seams on closed meshes (PSR output).
        """
        if weights is None:
            weights = torch.ones(3, device=vol.device, dtype=vol.dtype) / 3.0
        px = vol.mean(dim=2, keepdim=True).expand_as(vol)
        py = vol.mean(dim=1, keepdim=True).expand_as(vol)
        pz = vol.mean(dim=0, keepdim=True).expand_as(vol)
        w = weights.reshape(3, 1, 1, 1)
        w = w / w.sum().clamp_min(1e-12)
        return px * w[0] + py * w[1] + pz * w[2]

    def bake(self, shape: Tuple[int, int, int],
             layers: Sequence[TextureLayer],
             sigma: Optional[Tensor] = None) -> Dict[str, Any]:
        """Composite a layer stack; also returns a displacement field."""
        dev = next(self.pfc.parameters()).device if any(
            True for _ in self.pfc.parameters()) else torch.device("cpu")
        base = torch.full(shape, 0.5, device=dev)
        displacement = torch.zeros(shape, device=dev)
        detail: Dict[str, Any] = {}
        for layer in layers:
            L = self.generate_layer(shape, layer, sigma)
            if layer.triplanar:
                L = self.triplanar(L)
            if layer.scale != 1.0:
                L = (L - 0.5) * layer.scale + 0.5
            base = (1 - layer.opacity) * base + layer.opacity * _blend(base, L, layer.blend)
            displacement = displacement + layer.displacement_gain * (L - 0.5)
            detail[layer.name] = {"kind": layer.kind, "opacity": layer.opacity,
                                  "blend": layer.blend.value,
                                  "mean": float(L.mean()), "std": float(L.std())}
        return {"albedo_scalar": base.clamp(0, 1),
                "displacement": displacement,
                "layers": detail}


