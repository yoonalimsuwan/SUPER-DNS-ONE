class _Conv3dLaplacian(nn.Module):
    """
    [GPU-1] Vectorised staggered conservative stencil. No Python axis loops.
        d/dx[sigma df/dx] = (s_{i+1/2}(f_{i+1}-f_i) - s_{i-1/2}(f_i-f_{i-1}))/dx^2
        s_{i+1/2} = 0.5 (s_i + s_{i+1})
    torch.roll + elementwise arithmetic => CUDA-parallel, autograd-safe,
    periodic BC.
    """

    def __init__(self, dx: float, sigma_min: float = 1e-3):
        super().__init__()
        self.dx = dx
        self.sigma_min = sigma_min

    def forward(self, field: Tensor, sigma: Tensor) -> Tensor:
        dx2 = self.dx ** 2
        out = torch.zeros_like(field)
        for dim in range(field.dim()):
            fp = torch.roll(field, -1, dim)
            fm = torch.roll(field, +1, dim)
            sp = 0.5 * (sigma + torch.roll(sigma, -1, dim))
            sm = 0.5 * (sigma + torch.roll(sigma, +1, dim))
            out = out + (sp * (fp - field) - sm * (field - fm)) / dx2
        return out


class _FFTLaplacian(nn.Module):
    """
    [GPU-2] Spectral structural Laplacian.
        Lap_S u = sigma_bar Lap u  +  grad(sigma) . grad(u) + (sigma-sigma_bar) Lap u
    Homogeneous part O(N log N) in Fourier; heterogeneous correction by FD.
    """

    def __init__(self, dx: float):
        super().__init__()
        self.dx = dx
        self._k2: Optional[Tensor] = None
        self._kshape: Optional[Tuple] = None

    def _wavenumbers(self, shape, dev, dtype):
        if (self._k2 is not None and self._kshape == shape
                and self._k2.device == dev and self._k2.dtype == dtype):
            return self._k2
        dx = self.dx
        ks = []
        for i, n in enumerate(shape):
            if i == len(shape) - 1:
                ks.append(torch.fft.rfftfreq(n, d=dx / (2 * math.pi),
                                             dtype=dtype, device=dev))
            else:
                ks.append(torch.fft.fftfreq(n, d=dx / (2 * math.pi),
                                            dtype=dtype, device=dev))
        grids = torch.meshgrid(*ks, indexing="ij")
        k2 = sum(g ** 2 for g in grids)
        self._k2, self._kshape = k2, shape
        return k2

    def forward(self, field: Tensor, sigma: Tensor) -> Tensor:
        with _fp32_island(str(field.device.type)):
            f32, s32 = field.float(), sigma.float()
            n = f32.shape
            s_bar = s32.mean()
            k2 = self._wavenumbers(n, f32.device, f32.dtype)
            f_hat = torch.fft.rfftn(f32, norm="ortho")
            lap_hom = torch.fft.irfftn(-k2 * f_hat, s=n, norm="ortho") * s_bar

            ds = s32 - s_bar
            dx = self.dx
            lap_f = torch.zeros_like(f32)
            corr = torch.zeros_like(f32)
            for ax in range(f32.dim()):
                gf = (torch.roll(f32, -1, ax) - torch.roll(f32, +1, ax)) / (2 * dx)
                gds = (torch.roll(ds, -1, ax) - torch.roll(ds, +1, ax)) / (2 * dx)
                lap_f = lap_f + (torch.roll(f32, -1, ax) - 2 * f32
                                 + torch.roll(f32, +1, ax)) / dx ** 2
                corr = corr + gds * gf
            corr = corr + ds * lap_f
            return (lap_hom + corr).to(field.dtype)


class _RollLaplacian(nn.Module):
    """[roll] v1 reference implementation; mathematically identical."""

    def __init__(self, dx: float):
        super().__init__()
        self.dx = dx

    def forward(self, field: Tensor, sigma: Tensor) -> Tensor:
        dx2 = self.dx ** 2
        out = torch.zeros_like(field)
        for dim in range(field.dim()):
            fp = torch.roll(field, -1, dim)
            fm = torch.roll(field, +1, dim)
            sp = 0.5 * (sigma + torch.roll(sigma, -1, dim))
            sm = 0.5 * (sigma + torch.roll(sigma, +1, dim))
            out = out + (sp * (fp - field) - sm * (field - fm)) / dx2
        return out


def _build_laplacian_module(cfg: CahnHilliardConfig) -> nn.Module:
    if cfg.laplacian == "conv3d":
        return _Conv3dLaplacian(cfg.dx, cfg.sigma_min)
    if cfg.laplacian == "fft":
        return _FFTLaplacian(cfg.dx)
    return _RollLaplacian(cfg.dx)


def make_sigma_field(nx: int, ny: int, nz: int, background: float = 1.0,
                     inclusions: Optional[list] = None, device: str = "cpu",
                     dtype: torch.dtype = torch.float64) -> Tensor:
    """Build a piecewise structural sigma(x) field."""
    sigma = torch.full((nx, ny, nz), background, device=device, dtype=dtype)
    if inclusions:
        for inc in inclusions:
            sigma[inc["x0"]:inc["x1"], inc["y0"]:inc["y1"],
                  inc["z0"]:inc["z1"]] = inc["sigma"]
    return sigma


class StructuralCahnHilliard3D(nn.Module):
    """
    3D Structural Cahn-Hilliard.  (CH-1) mu = u^3-u - eps^2 Lap_S u
                                  (CH-2) u_t = M Lap_S mu
    """

    def __init__(self, cfg: Optional[CahnHilliardConfig] = None, ssc=None):
        super().__init__()
        self.cfg = cfg or CahnHilliardConfig()
        self.ssc = ssc
        self._lap: nn.Module = _build_laplacian_module(self.cfg)
        self._k2_imex: Optional[Tensor] = None
        self._imex_shape: Optional[Tuple] = None

    def _structural_laplacian(self, field: Tensor, sigma: Tensor) -> Tensor:
        sigma_s = _softplus_floor(sigma, self.cfg.sigma_min)
        return self._lap(field, sigma_s)

    def compute_chemical_potential(self, u: Tensor, sigma: Tensor) -> Tensor:
        return (u ** 3 - u) - (self.cfg.epsilon ** 2) * self._structural_laplacian(u, sigma)

    def _step_explicit(self, u: Tensor, sigma: Tensor) -> Tensor:
        mu = self.compute_chemical_potential(u, sigma)
        return u + self.cfg.dt * self.cfg.mobility * self._structural_laplacian(mu, sigma)

    def _get_k2_imex(self, shape, device, dtype) -> Tensor:
        if (self._k2_imex is not None and self._imex_shape == shape
                and self._k2_imex.device == device
                and self._k2_imex.dtype == dtype):
            return self._k2_imex
        dx = self.cfg.dx
        ks = []
        for i, n in enumerate(shape):
            if i == len(shape) - 1:
                ks.append(torch.fft.rfftfreq(n, d=dx / (2 * math.pi),
                                             dtype=dtype, device=device))
            else:
                ks.append(torch.fft.fftfreq(n, d=dx / (2 * math.pi),
                                            dtype=dtype, device=device))
        grids = torch.meshgrid(*ks, indexing="ij")
        self._k2_imex = sum(g ** 2 for g in grids)
        self._imex_shape = shape
        return self._k2_imex

    def _step_imex(self, u: Tensor, sigma: Tensor) -> Tensor:
        cfg = self.cfg
        with _fp32_island(str(u.device.type)):
            u32 = u.float()
            k2 = self._get_k2_imex(u32.shape, u32.device, u32.dtype)
            nonlin = self._structural_laplacian(u32 ** 3 - u32, sigma)
            u_hat = torch.fft.rfftn(u32, norm="ortho")
            rhs_hat = torch.fft.rfftn(nonlin.float(), norm="ortho")
            denom = 1.0 + cfg.dt * cfg.mobility * (cfg.epsilon ** 2) * (k2 ** 2)
            new_hat = (u_hat + cfg.dt * cfg.mobility * rhs_hat) / denom
            return torch.fft.irfftn(new_hat, s=u32.shape, norm="ortho").to(u.dtype)

    def step(self, u: Tensor, sigma: Optional[Tensor] = None) -> Tensor:
        sigma = self._resolve_sigma(u, sigma)
        if self.cfg.scheme == "explicit":
            return self._step_explicit(u, sigma)
        return self._step_imex(u, sigma)

    def structural_energy(self, u: Tensor, sigma: Optional[Tensor] = None) -> Tensor:
        """E_R[u] = int [ 1/4 (u^2-1)^2 + 1/2 eps^2 sigma |grad u|^2 ] dV"""
        sigma = self._resolve_sigma(u, sigma)
        dx = self.cfg.dx
        bulk = 0.25 * (u ** 2 - 1.0) ** 2
        g2 = 0.0
        for ax in range(u.dim()):
            g2 = g2 + ((torch.roll(u, -1, ax) - torch.roll(u, +1, ax)) / (2 * dx)) ** 2
        iface = 0.5 * (self.cfg.epsilon ** 2) * sigma * g2
        return torch.sum(bulk + iface) * (dx ** u.dim())

    def total_mass(self, u: Tensor) -> Tensor:
        return torch.sum(u) * (self.cfg.dx ** u.dim())

    def evolve(self, u: Tensor, sigma: Optional[Tensor] = None, n_steps: int = 100,
               log_interval: int = 0) -> Tuple[Tensor, Dict[str, list]]:
        sigma = self._resolve_sigma(u, sigma)
        hist: Dict[str, list] = {"step": [], "energy": [], "mass": []}
        for i in range(n_steps):
            u = self.step(u, sigma)
            if log_interval and i % log_interval == 0:
                with torch.no_grad():
                    hist["step"].append(i)
                    hist["energy"].append(float(self.structural_energy(u, sigma)))
                    hist["mass"].append(float(self.total_mass(u)))
        return u, hist

    def _resolve_sigma(self, u: Tensor, sigma: Optional[Tensor]) -> Tensor:
        if sigma is None:
            sigma = torch.ones_like(u)
        return _softplus_floor(sigma, self.cfg.sigma_min)


class ThinFilmStructuralCahnHilliard3D(StructuralCahnHilliard3D):
    """[TF-1] Degenerate mobility M(u) = softplus(u)^3 + Mullins-Sekerka term."""

    def __init__(self, cfg: Optional[CahnHilliardConfig] = None, ssc=None):
        cfg = cfg or CahnHilliardConfig(thin_film=True)
        super().__init__(cfg, ssc)

    def get_thin_film_mobility(self, u: Tensor) -> Tensor:
        return F.softplus(u, beta=_SOFTPLUS_B) ** 3

    def _mobility_weighted_laplacian(self, field, sigma, M) -> Tensor:
        sigma_eff = _softplus_floor(M * sigma, self.cfg.sigma_min)
        return self._lap(field, sigma_eff)

    def _step_explicit_tf(self, u, sigma):
        M = self.get_thin_film_mobility(u)
        mu = self.compute_chemical_potential(u, sigma)
        rhs = self._mobility_weighted_laplacian(mu, sigma, M)
        if self.cfg.surface_diffusion:
            lap_u = self._structural_laplacian(u, sigma)
            rhs = rhs - self.cfg.kappa_s * self._structural_laplacian(M * lap_u, sigma)
        return u + self.cfg.dt * rhs

    def _step_imex_tf(self, u, sigma):
        cfg = self.cfg
        with _fp32_island(str(u.device.type)):
            u32 = u.float()
            M = self.get_thin_film_mobility(u32)
            M_mean = M.mean()
            k2 = self._get_k2_imex(u32.shape, u32.device, u32.dtype)
            nonlin = self._mobility_weighted_laplacian(u32 ** 3 - u32, sigma, M)
            if cfg.surface_diffusion:
                lap_u = self._structural_laplacian(u32, sigma)
                nonlin = nonlin - cfg.kappa_s * self._structural_laplacian(M * lap_u, sigma)
            u_hat = torch.fft.rfftn(u32, norm="ortho")
            rhs_hat = torch.fft.rfftn(nonlin.float(), norm="ortho")
            denom = 1.0 + cfg.dt * M_mean * (cfg.epsilon ** 2) * (k2 ** 2)
            new_hat = (u_hat + cfg.dt * rhs_hat) / denom
            return torch.fft.irfftn(new_hat, s=u32.shape, norm="ortho").to(u.dtype)

    def step(self, u, sigma=None):
        sigma = self._resolve_sigma(u, sigma)
        return (self._step_explicit_tf(u, sigma) if self.cfg.scheme == "explicit"
                else self._step_imex_tf(u, sigma))

    def thin_film_energy(self, u, sigma=None, A_hamaker: float = 0.0) -> Tensor:
        sigma = self._resolve_sigma(u, sigma)
        E = self.structural_energy(u, sigma)
        if A_hamaker:
            E = E - 0.5 * A_hamaker * torch.sum(u ** 2) * (self.cfg.dx ** u.dim())
        return E


class PhaseFieldCrystal3D(StructuralCahnHilliard3D):
    """
    [PFC-1] 6th-order structural PFC.
        mu = r u + u^3 + (1 + Lap_S)^2 u = (r u + u^3) + u + 2 Lap_S u + Lap_S^2 u
    Three nested structural Laplacians per mu; a fourth for u_t = Lap_S mu.
    """

    def __init__(self, cfg: Optional[CahnHilliardConfig] = None, ssc=None):
        cfg = cfg or CahnHilliardConfig(pfc_r=-0.5)
        super().__init__(cfg, ssc)

    def compute_pfc_chemical_potential(self, u, sigma):
        r = self.cfg.pfc_r
        lap1 = self._structural_laplacian(u, sigma)
        lap2 = self._structural_laplacian(lap1, sigma)
        return (r * u + u ** 3) + (u + 2.0 * lap1 + lap2)

    def compute_chemical_potential(self, u, sigma):
        return self.compute_pfc_chemical_potential(u, sigma)

    def _step_pfc_explicit(self, u, sigma):
        mu = self.compute_pfc_chemical_potential(u, sigma)
        return u + self.cfg.dt * self.cfg.mobility * self._structural_laplacian(mu, sigma)

    def _step_pfc_imex(self, u, sigma):
        cfg = self.cfg
        with _fp32_island(str(u.device.type)):
            u32 = u.float()
            k2 = self._get_k2_imex(u32.shape, u32.device, u32.dtype)
            s_bar = sigma.mean()
            lap1 = self._structural_laplacian(u32, sigma)
            nonlin = (cfg.pfc_r * u32 + u32 ** 3) + u32 + 2.0 * lap1
            u_hat = torch.fft.rfftn(u32, norm="ortho")
            nl_hat = torch.fft.rfftn(nonlin.float(), norm="ortho")
            k4, k6 = k2 ** 2, k2 ** 3
            denom = 1.0 + cfg.dt * cfg.mobility * s_bar * (k2 + k4 + k6)
            new_hat = (u_hat + cfg.dt * cfg.mobility * nl_hat) / denom
            return torch.fft.irfftn(new_hat, s=u32.shape, norm="ortho").to(u.dtype)

    def step(self, u, sigma=None):
        sigma = self._resolve_sigma(u, sigma)
        return (self._step_pfc_explicit(u, sigma) if self.cfg.scheme == "explicit"
                else self._step_pfc_imex(u, sigma))

    def pfc_energy(self, u, sigma=None) -> Tensor:
        sigma = self._resolve_sigma(u, sigma)
        dx, r = self.cfg.dx, self.cfg.pfc_r
        lap1 = self._structural_laplacian(u, sigma)
        lap2 = self._structural_laplacian(lap1, sigma)
        op = u + 2.0 * lap1 + lap2
        return torch.sum(0.5 * r * u ** 2 + 0.25 * u ** 4 + 0.5 * u * op) * (dx ** u.dim())


