class WENO5Advector(nn.Module):
    """
    [C] Jiang-Shu WENO-5 with LF flux splitting, batched over all non-swept
    axes. DIFF-FIX 2 preserved (_logsumexp_max for the wave speed).
    HONEST: scalar advection only. Not DNS, no shock-capturing guarantee.
    """

    def __init__(self):
        super().__init__()

    def _flux_last(self, q: Tensor, vel: Tensor, dx: float) -> Tensor:
        def roll(t, k):
            return torch.roll(t, k, dims=-1)
        vf = 0.5 * (vel + roll(vel, -1))
        alpha = _logsumexp_max(_soft_abs(vf)) + 1e-12
        eps = 1e-6

        def fp(x, vv):
            return 0.5 * (vv * x + alpha * x)

        def fm(x, vv):
            return 0.5 * (vv * x - alpha * x)

        qm2, qm1, q0 = roll(q, 2), roll(q, 1), q
        qp1, qp2, qp3 = roll(q, -1), roll(q, -2), roll(q, -3)
        vm2, vm1, v0 = roll(vel, 2), roll(vel, 1), vel
        vp1, vp2, vp3 = roll(vel, -1), roll(vel, -2), roll(vel, -3)

        f0, f1, f2 = fp(qm2, vm2), fp(qm1, vm1), fp(q0, v0)
        f3, f4, f5 = fp(qp1, vp1), fp(qp2, vp2), fp(qp3, vp3)
        p0 = (1 / 3) * f0 - (7 / 6) * f1 + (11 / 6) * f2
        p1 = (-1 / 6) * f1 + (5 / 6) * f2 + (1 / 3) * f3
        p2 = (1 / 3) * f2 + (5 / 6) * f3 - (1 / 6) * f4
        b0 = (13 / 12) * (f0 - 2 * f1 + f2) ** 2 + .25 * (f0 - 4 * f1 + 3 * f2) ** 2
        b1 = (13 / 12) * (f1 - 2 * f2 + f3) ** 2 + .25 * (f1 - f3) ** 2
        b2 = (13 / 12) * (f2 - 2 * f3 + f4) ** 2 + .25 * (3 * f2 - 4 * f3 + f4) ** 2
        a0, a1, a2 = .1 / (eps + b0) ** 2, .6 / (eps + b1) ** 2, .3 / (eps + b2) ** 2
        Fp = (a0 * p0 + a1 * p1 + a2 * p2) / _softplus_floor(a0 + a1 + a2, 1e-12)

        g0, g1, g2 = fm(q0, v0), fm(qp1, vp1), fm(qp2, vp2)
        g3, g4, g5 = fm(qp3, vp3), fm(roll(q, -4), roll(vel, -4)), fm(roll(q, -5), roll(vel, -5))
        m0 = (1 / 3) * g2 + (5 / 6) * g1 - (1 / 6) * g0
        m1 = (-1 / 6) * g3 + (5 / 6) * g2 + (1 / 3) * g1
        m2 = (1 / 3) * g4 - (7 / 6) * g3 + (11 / 6) * g2
        c0 = (13 / 12) * (g0 - 2 * g1 + g2) ** 2 + .25 * (g0 - 4 * g1 + 3 * g2) ** 2
        c1 = (13 / 12) * (g1 - 2 * g2 + g3) ** 2 + .25 * (g1 - g3) ** 2
        c2 = (13 / 12) * (g2 - 2 * g3 + g4) ** 2 + .25 * (3 * g2 - 4 * g3 + g4) ** 2
        w0, w1, w2 = .3 / (eps + c0) ** 2, .6 / (eps + c1) ** 2, .1 / (eps + c2) ** 2
        Fm = (w0 * m0 + w1 * m1 + w2 * m2) / _softplus_floor(w0 + w1 + w2, 1e-12)

        flux = Fp + Fm
        return -(flux - roll(flux, 1)) / dx

    def _sweep(self, q, vel, axis, dx):
        if axis == q.dim() - 1:
            return self._flux_last(q, vel, dx)
        return torch.moveaxis(
            self._flux_last(torch.moveaxis(q, axis, -1),
                            torch.moveaxis(vel, axis, -1), dx),
            -1, axis)

    def advect(self, q: Tensor, vel: List[Tensor], dx: float, dt: float) -> Tensor:
        axes = list(range(q.dim() - len(vel), q.dim()))
        out = q
        for ax, vv in zip(axes, vel):
            out = out + 0.5 * dt * self._sweep(out, vv, ax, dx)
        for ax, vv in zip(reversed(axes), reversed(vel)):
            out = out + 0.5 * dt * self._sweep(out, vv, ax, dx)
        return out

    def coherence(self, cur: Tensor, prev: Tensor, flow: List[Tensor],
                  dx: float, dt: float) -> Dict[str, Tensor]:
        prev_adv = self.advect(prev, flow, dx, dt)
        resid = cur - prev_adv
        denom = _softplus_floor(cur.abs().mean().detach(), 1e-8)
        return {"previous_advected": prev_adv,
                "coherence": torch.exp(-(resid.abs().mean() / denom)),
                "residual": resid}


@dataclass
class VideoConfig:
    n_frames: int = 8
    dx: float = 1.0
    dt: float = 0.05
    ch_steps_per_frame: int = 4
    temporal_weight: float = 0.35
    mode: str = "2d"           # "2d" | "3d"
    watertight_3d: bool = True


class VideoForge2D3D(nn.Module):
    """
    [D] Video pipeline.

    2D: per-frame Ambrosio-Tortorelli vectorisation + WENO5 temporal coherence
        so the vector decomposition does not flicker between frames.
    3D: the embedded CH/PFC field evolves in real time and each frame is
        reconstructed with DifferentiablePoissonReconstructor -> an animated
        sequence of WATERTIGHT meshes.

    HONEST: 3D mode is memory-heavy; use gradient checkpointing and the
    tiled renderer for cinema resolutions.
    """

    def __init__(self, cfg: Optional[VideoConfig] = None):
        super().__init__()
        self.cfg = cfg or VideoConfig()
        c = CahnHilliardConfig(dx=self.cfg.dx, epsilon=1.5, dt=self.cfg.dt,
                               laplacian="conv3d", scheme="imex",
                               dtype=torch.float32)
        self.ch = StructuralCahnHilliard3D(c)
        self.pfc = PhaseFieldCrystal3D(CahnHilliardConfig(
            dx=self.cfg.dx, epsilon=1.5, dt=self.cfg.dt * 0.1,
            pfc_r=-0.5, laplacian="conv3d", scheme="imex", dtype=torch.float32))
        self.weno = WENO5Advector()
        self.vq = VectorGradeBitmapEngine()
        self.psr = DifferentiablePoissonReconstructor(
            PSRConfig(pad=3, lam=6.0))
        self.temporal_w = nn.Parameter(torch.tensor(self.cfg.temporal_weight))

    def run_2d(self, frames: Tensor) -> Dict[str, Any]:
        """frames: (T, 3, H, W)."""
        T = frames.shape[0]
        us, vs, coh = [], [], []
        prev_u, prev_v = None, None
        w = torch.sigmoid(self.temporal_w)
        for t in range(T):
            out = self.vq(frames[t:t + 1], dx=self.cfg.dx)
            u, v = out["u"], out["v"]
            if prev_u is not None:
                flow = [torch.zeros_like(u[:, :1]), torch.zeros_like(u[:, :1])]
                cc = self.weno.coherence(u, prev_u, flow, self.cfg.dx, self.cfg.dt)
                u = (1 - w) * u + w * cc["previous_advected"]
                vv = self.weno.coherence(v, prev_v, flow, self.cfg.dx, self.cfg.dt)
                v = (1 - w) * v + w * vv["previous_advected"]
                coh.append(float(cc["coherence"].detach()))
            prev_u, prev_v = u.detach(), v.detach()
            us.append(u)
            vs.append(v)
        return {"u": torch.cat(us, 0), "v": torch.cat(vs, 0),
                "n_frames": T,
                "mean_temporal_coherence": float(np.mean(coh)) if coh else 1.0,
                "temporal_weight": float(torch.sigmoid(self.temporal_w))}

    def run_3d(self, u0: Tensor, sigma: Optional[Tensor] = None,
               solver: str = "ch") -> Dict[str, Any]:
        """Evolve a 3-D phase field and reconstruct watertight meshes per frame."""
        if sigma is None:
            sigma = torch.ones_like(u0)
        sol = self.ch if solver == "ch" else self.pfc
        u = u0
        meshes, checks = [], []
        for f in range(self.cfg.n_frames):
            for _ in range(self.cfg.ch_steps_per_frame):
                u = sol.step(u, sigma)
            if self.cfg.watertight_3d:
                rec = self.psr.reconstruct(u, dx=self.cfg.dx)
                meshes.append(rec["mesh"])
                checks.append({
                    "frame": f,
                    "watertight_guarantee_holds": rec["watertight_guarantee_holds"],
                    "watertight_measured": rec.get("watertight_measured"),
                    "boundary_edges": (rec.get("euler", {}) or {}).get("boundary_edges"),
                    "chi": (rec.get("euler", {}) or {}).get("chi"),
                    "n_faces": rec["mesh"]["n_faces"],
                })
            else:
                meshes.append(self.psr.mc.extract(u, dx=self.cfg.dx))
                checks.append({"frame": f, "watertight_guarantee_holds": False})
        return {"final_field": u, "meshes": meshes, "checks": checks,
                "all_watertight": all(c.get("watertight_measured", False)
                                      for c in checks) if self.cfg.watertight_3d else None}

