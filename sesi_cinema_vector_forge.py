class NoZenoGate:
    """
    [P] Hysteresis gate bounding the refinement EVENT COUNT.
        N(T) <= (E_max + D) / delta_min
    Bounds events, NOT error and NOT uncertainty.
    """

    def __init__(self, theta_hi: float = 0.2, theta_lo: float = 0.05):
        if theta_hi <= theta_lo:
            raise ValueError("theta_hi > theta_lo required")
        self.theta_hi, self.theta_lo = theta_hi, theta_lo
        self.delta_min = theta_hi - theta_lo
        self.stress_acc = 0.0
        self.E_max = 0.0
        self.D = 0.0
        self.event_count = 0
        self.armed = True

    def update(self, stress: float) -> Dict[str, Any]:
        self.stress_acc = max(self.stress_acc, stress)
        self.E_max = max(self.E_max, self.stress_acc)
        allowed = False
        if self.armed and self.stress_acc > self.theta_hi:
            allowed = True
            self.event_count += 1
            self.D += self.stress_acc
            self.stress_acc = 0.0
            self.armed = False
        elif (not self.armed) and self.stress_acc < self.theta_lo:
            self.armed = True
        else:
            self.stress_acc *= 0.9
        bound = (self.E_max + self.D) / self.delta_min
        return {"allowed": allowed, "event_count": self.event_count,
                "bound_rhs": bound,
                "invariant_holds": self.event_count <= bound + 1e-6}


class DorflerMarker:
    """[P] Bulk-chasing: smallest set carrying theta of the total error."""

    def __init__(self, theta: float = 0.5):
        if not 0.0 < theta < 1.0:
            raise ValueError("theta must be in (0,1)")
        self.theta = theta

    def mark(self, err: Tensor) -> Tensor:
        flat = err.detach().flatten()
        total = float(flat.sum())
        if total <= 0:
            return torch.zeros_like(err, dtype=torch.bool)
        order = torch.argsort(flat, descending=True)
        cum = torch.cumsum(flat[order], 0)
        k = int(torch.searchsorted(cum, self.theta * total).item()) + 1
        k = max(1, min(k, flat.numel()))
        mask = torch.zeros_like(flat, dtype=torch.bool)
        mask[order[:k]] = True
        return mask.reshape(err.shape)


@dataclass
class CarpetAMRConfig:
    max_level: int = 6
    dorfler_theta: float = 0.55
    theta_hi: float = 0.22
    theta_lo: float = 0.06
    use_no_zeno: bool = True
    use_fractal_measure: bool = True
    d_f: float = CARPET_DF
    edge_weight: float = 1.0
    texture_weight: float = 0.35
    measure_weight: float = 0.25


class CarpetAMRController(nn.Module):
    """
    [C/D] Fractal-measure-aware AMR.

    ERROR INDICATOR
        eta_K = w_e |grad u| (1-v)  +  w_t VarBox(u)^{1/2}  +  w_m |sigma_K - 1|
                edge term           texture term            FRACTAL MEASURE term

    FRACTAL MEASURE CONDUCTIVITY  [D]
        sigma_K = h^{d_f - d},   h = 2^{-level}
    This is the carpet's Hausdorff measure restricted to a cell, and it is fed
    directly into the embedded Structural CH Laplacian as the heterogeneous
    conductivity. That is what makes this AMR "carpet-level" rather than a
    plain gradient refiner: refinement AND diffusion both see the fractal.

    d_f comes from FractalRegistry for the carpet, or from NonPCFCalibrator
    for any other calibrated set -- with the [O] caveat attached.
    """

    def __init__(self, cfg: Optional[CarpetAMRConfig] = None):
        super().__init__()
        self.cfg = cfg or CarpetAMRConfig()
        self.marker = DorflerMarker(self.cfg.dorfler_theta)
        self.gate = (NoZenoGate(self.cfg.theta_hi, self.cfg.theta_lo)
                     if self.cfg.use_no_zeno else None)
        self.w_edge = nn.Parameter(torch.tensor(self.cfg.edge_weight))
        self.w_tex = nn.Parameter(torch.tensor(self.cfg.texture_weight))
        self.w_meas = nn.Parameter(torch.tensor(self.cfg.measure_weight))
        self.register_buffer("d_f", torch.tensor(float(self.cfg.d_f)))

    def set_fractal(self, calib: FractalCalibration) -> None:
        """Adopt a calibrated non-PCF exponent set. Logs the [O] caveat."""
        self.d_f = torch.tensor(float(calib.d_f_measured))
        logger.info("AMR fractal set to %s: d_f=%.4f d_w=%.4f alpha=%.4f | %s",
                    calib.name, calib.d_f_measured, calib.d_w_measured,
                    calib.alpha_caputo, calib.label)

    def fractal_sigma(self, shape, level: int, device, dtype) -> Tensor:
        """sigma = h^{d_f - d}, h = 2^{-level}."""
        h = 2.0 ** (-level)
        d_embed = len(shape)
        val = h ** (float(self.d_f) - d_embed)
        return torch.full(shape, float(val), device=device, dtype=dtype)

    def error_indicator(self, u: Tensor, v: Tensor, dx: float,
                        level: int = 2) -> Tensor:
        """eta_K, spatial dims are the trailing ones."""
        g = 0.0
        for ax in range(2, u.dim()):
            g = g + ((torch.roll(u, -1, ax) - torch.roll(u, 1, ax))
                     / (2 * dx)).abs()
        edge = g * (1.0 - v)

        k = 3
        pad = k // 2
        dims = u.dim() - 2
        pool = F.avg_pool2d if dims == 2 else F.avg_pool3d
        mean = pool(u, k, 1, pad)
        var = (pool(u * u, k, 1, pad) - mean ** 2).clamp_min(0).sqrt()

        sigma = self.fractal_sigma(u.shape, level, u.device, u.dtype)
        meas = (sigma - 1.0).abs()

        return (self.w_edge.abs() * edge + self.w_tex.abs() * var
                + self.w_meas.abs() * meas)

    def adapt(self, u: Tensor, v: Tensor, dx: float, level: int = 2
              ) -> Dict[str, Any]:
        eta = self.error_indicator(u, v, dx, level)
        stress = float(eta.amax() / (eta.mean() + 1e-12))
        if self.gate is not None:
            g = self.gate.update(stress)
            if not g["invariant_holds"]:
                logger.error("No-Zeno INVARIANT VIOLATED: %d > %.3f",
                             g["event_count"], g["bound_rhs"])
                return {"refined": False, "blocked": True,
                        "reason": "no_zeno_invariant_violated", "stress": stress}
            if not g["allowed"]:
                return {"refined": False, "blocked": True,
                        "reason": "gate_closed", "stress": stress,
                        "no_zeno_events": g["event_count"]}
        mask = self.marker.mark(eta)
        frac = float(mask.float().mean())
        return {
            "refined": bool(mask.any()), "blocked": False, "stress": stress,
            "mask": mask, "refined_fraction": frac, "level": level,
            "estimated_speedup": 1.0 / max(frac * 1.15, 1e-3),
            "no_zeno_events": self.gate.event_count if self.gate else 0,
            "d_f": float(self.d_f),
        }


