class SESICinemaVectorForge(nn.Module):
    """
    Unified forge:
      prompt -> transformer -> (u0, sigma, pfc_r)
             -> world-model preview (optional)
             -> embedded CH/PFC evolution
             -> carpet AMR (d_f from the calibrated fractal)
             -> 2D: Ambrosio-Tortorelli vector-grade bitmap + realism raster
             -> 3D: differentiable Poisson -> WATERTIGHT marching-cubes mesh
             -> OCIO colour transform
             -> export: SVG paths / OBJ mesh / EXR-ready linear
    """

    def __init__(self, cfg: Optional[ForgeConfig] = None):
        super().__init__()
        self.cfg = cfg or ForgeConfig()
        dev = self.cfg.device

        self.calibrator = NonPCFCalibrator()
        specs = FractalRegistry.all_specs()
        self.specs = specs
        self.calibration: Optional[FractalCalibration] = None

        self.amr = CarpetAMRController(CarpetAMRConfig(d_f=CARPET_DF))
        self.vq = VectorGradeBitmapEngine(
            ATConfig(n_steps=self.cfg.at_steps), amr=self.amr)
        self.realism = BitmapRealismRenderer(supersample=self.cfg.supersample)
        self.psr = DifferentiablePoissonReconstructor(
            PSRConfig(pad=self.cfg.psr_pad, lam=self.cfg.psr_lam))
        self.mc = self.psr.mc
        self.textures = ProceduralTextureStack(
            ch_epsilon=self.cfg.ch_epsilon, pfc_r=self.cfg.pfc_r)
        self.video = VideoForge2D3D(VideoConfig(dx=self.cfg.dx, dt=1e-2))
        self.prompt = PromptShapeTransformer(
            PromptShapeConfig(grid=max(8, self.cfg.grid3d // 2)))
        self.world = ShapeWorldModel(
            PromptShapeConfig(grid=max(8, self.cfg.grid3d // 2)))
        self.ocio_loader: Optional[OCIOConfigLoader] = None
        self.ocio: Optional[OCIOProcessor] = None

        ch_cfg = CahnHilliardConfig(dx=self.cfg.dx, epsilon=self.cfg.ch_epsilon,
                                    dt=self.cfg.ch_dt, laplacian="conv3d",
                                    scheme="imex", dtype=torch.float32,
                                    device=dev)
        self.ch = StructuralCahnHilliard3D(ch_cfg)
        self.pfc = PhaseFieldCrystal3D(CahnHilliardConfig(
            dx=self.cfg.dx, epsilon=self.cfg.ch_epsilon,
            dt=self.cfg.ch_dt * 0.1, pfc_r=self.cfg.pfc_r,
            laplacian="conv3d", scheme="imex", dtype=torch.float32, device=dev))
        self.thinfilm = ThinFilmStructuralCahnHilliard3D(CahnHilliardConfig(
            dx=self.cfg.dx, epsilon=self.cfg.ch_epsilon, dt=self.cfg.ch_dt,
            thin_film=True, surface_diffusion=True, kappa_s=0.01,
            laplacian="conv3d", scheme="explicit", dtype=torch.float32, device=dev))

    # ── fractal calibration ─────────────────────────────────────────────
    def calibrate_to(self, name: Optional[str] = None,
                     level: Optional[int] = None) -> FractalCalibration:
        name = name or self.cfg.fractal
        level = level or self.cfg.calibration_level
        if name not in self.specs:
            raise KeyError(f"unknown fractal {name!r}; have {list(self.specs)}")
        calib = self.calibrator.calibrate(self.specs[name], level=level,
                                          n_walks=256, n_steps=200)
        self.calibration = calib
        self.amr.set_fractal(calib)
        return calib

    def calibrate_all(self, level: int = 3) -> Dict[str, FractalCalibration]:
        return self.calibrator.calibrate_all(level=level, n_walks=192, n_steps=180)

    # ── OCIO ────────────────────────────────────────────────────────────
    def load_ocio(self, path: str) -> Dict[str, Any]:
        self.ocio_loader = OCIOConfigLoader.from_file(path)
        self.ocio = OCIOProcessor(self.ocio_loader)
        return self.ocio_loader.summary()

    def load_ocio_dict(self, data: Dict[str, Any]) -> Dict[str, Any]:
        self.ocio_loader = OCIOConfigLoader.from_dict(data)
        self.ocio = OCIOProcessor(self.ocio_loader)
        return self.ocio_loader.summary()

    def apply_ocio(self, rgb: Tensor, src: str, dst: str) -> Tensor:
        if self.ocio is None:
            raise OCIOError("no OCIO config loaded; call load_ocio() first")
        lead = rgb.shape[:-1]
        flat = rgb.reshape(-1, 3)
        out = self.ocio.convert(flat, src, dst)
        return out.reshape(*lead, 3)

    # ── field generation ────────────────────────────────────────────────
    def make_field(self, grid: int, seed: int = 0,
                   sigma: Optional[Tensor] = None,
                   solver: str = "ch", steps: Optional[int] = None,
                   amp: float = 0.2) -> Tuple[Tensor, Tensor]:
        dev = next(self.ch.parameters()).device if any(
            True for _ in self.ch.parameters()) else torch.device(self.cfg.device)
        g = torch.Generator(device="cpu").manual_seed(seed)
        u = (torch.rand(grid, grid, grid, generator=g) * 2 - 1) * amp
        u = u.to(dev)
        if sigma is None:
            sigma = self.amr.fractal_sigma((grid, grid, grid), 2, dev,
                                           torch.float32)
        sol = {"ch": self.ch, "pfc": self.pfc, "thin_film": self.thinfilm}[solver]
        n = steps if steps is not None else self.cfg.ch_steps
        for _ in range(n):
            u = sol.step(u, sigma)
        return u, sigma

    # ── 2D path ─────────────────────────────────────────────────────────
    def vector_grade_2d(self, image: Tensor,
                        realism: bool = True) -> Dict[str, Any]:
        out = self.vq(image, dx=self.cfg.dx)
        res = {"vector_grade": out}
        if realism:
            res["realism"] = self.realism(out["u"], out["v"])
        res["svg"] = self.extract_svg_paths(out["u"], out["v"])
        return res

    def extract_svg_paths(self, u: Tensor, v: Tensor,
                          dp_epsilon: float = 0.35) -> Dict[str, Any]:
        """Marching-squares on the AT edge field -> SVG-ready polylines."""
        from_ = v[0].mean(0) if v.dim() == 4 else v.mean(0)
        K = (from_ < 0.5).float()
        gx = torch.roll(K, -1, 1) - torch.roll(K, 1, 1)
        gy = torch.roll(K, -1, 0) - torch.roll(K, 1, 0)
        contour = ((gx.abs() + gy.abs()) > 0.5)
        ys, xs = torch.nonzero(contour, as_tuple=True)
        pts = torch.stack([xs.float(), ys.float()], -1)
        H, W = K.shape
        n = min(pts.shape[0], 40000)
        norm = (pts[:n] / torch.tensor([W, H], device=pts.device,
                                       dtype=pts.dtype))
        d = ["<?xml version=\"1.0\" encoding=\"UTF-8\"?>",
             f"<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 {W} {H}\">"]
        if n > 1:
            step = max(1, n // 400)
            sub = norm[::step]
            path = "M " + " ".join(f"{p[0]*W:.2f} {p[1]*H:.2f}" for p in sub[:1])
            path += " " + " ".join(f"L {p[0]*W:.2f} {p[1]*H:.2f}" for p in sub[1:])
            d.append(f"<path d=\"{path}\" fill=\"none\" stroke=\"#111\" "
                     f"stroke-width=\"1\"/>")
        d.append("</svg>")
        return {"svg_text": "\n".join(d), "n_contour_points": int(pts.shape[0]),
                "stroke_coverage": float(K.mean()),
                "fill_coverage": float((from_ > 0.95).float().mean()),
                "resolution_independent": True}

    # ── 3D path ─────────────────────────────────────────────────────────
    def watertight_3d(self, u: Optional[Tensor] = None,
                      grid: Optional[int] = None,
                      seed: int = 0, solver: str = "ch") -> Dict[str, Any]:
        if u is None:
            u, _ = self.make_field(grid or self.cfg.grid3d, seed=seed, solver=solver)
        rec = self.psr.reconstruct(u, dx=self.cfg.dx)
        mesh = rec["mesh"]
        out = {
            "rec": rec,
            "mesh": mesh,
            "obj": (MarchingCubesExtractor.to_obj(mesh["vertices"], mesh["faces"])
                    if mesh["n_faces"] else ""),
            "watertight_guarantee_holds": rec["watertight_guarantee_holds"],
            "watertight_measured": rec.get("watertight_measured"),
            "euler": rec.get("euler"),
            "n_vertices": mesh["n_vertices"],
            "n_faces": mesh["n_faces"],
        }
        if mesh["n_faces"]:
            baked = self.textures.bake(
                u.shape,
                [TextureLayer("grain", "pfc", 0.6, BlendMode.OVERLAY, steps=8),
                 TextureLayer("marble", "ch", 0.4, BlendMode.SCREEN, steps=8),
                 TextureLayer("fractal", "carpet_sigma", 0.3,
                              BlendMode.SOFT_LIGHT)])
            out["material"] = {
                "albedo_mean": float(baked["albedo_scalar"].mean()),
                "albedo_std": float(baked["albedo_scalar"].std()),
                "displacement_range": (float(baked["displacement"].min()),
                                       float(baked["displacement"].max())),
                "layers": baked["layers"],
            }
        return out

    # ── prompt path ─────────────────────────────────────────────────────
    def shape_from_prompt(self, prompt: str, use_world_preview: bool = True,
                          simulate: bool = True) -> Dict[str, Any]:
        cond = self.prompt([prompt])
        res: Dict[str, Any] = {"conditioning": {
            k: (v.shape if torch.is_tensor(v) else v) for k, v in cond.items()}}
        g = cond["u0"].shape[-1]

        if use_world_preview:
            wm = self.world(cond["u0"])
            res["world_preview"] = {
                "imagined_shape": tuple(wm["imagined_fields"].shape),
                "predicted_reward": float(wm["predicted_reward"].mean()),
                "predicted_vgi": float(wm["predicted_vector_grade_index"].mean()),
                "kl": float(wm["kl"].mean()),
                "note": "[D] preview only; untrained weights give noise",
            }

        if simulate:
            sigma = cond["sigma"][0]
            if sigma.shape != (g, g, g):
                sigma = F.interpolate(
                    sigma.reshape(1, 1, g, g, g), size=(g, g, g),
                    mode="trilinear", align_corners=False).reshape(g, g, g)
            u = cond["u0"][0] * 0.2
            r = float(cond["pfc_r"][0])
            self.pfc.cfg.pfc_r = r
            for _ in range(max(4, self.cfg.ch_steps // 2)):
                u = self.pfc.step(u, sigma)
            rec = self.psr.reconstruct(u, dx=self.cfg.dx)
            m = rec["mesh"]
            res["simulated"] = {
                "pfc_r": r,
                "n_vertices": m["n_vertices"], "n_faces": m["n_faces"],
                "watertight_guarantee_holds": rec["watertight_guarantee_holds"],
                "watertight_measured": rec.get("watertight_measured"),
                "chi": (rec.get("euler", {}) or {}).get("chi"),
            }
        return res

    # ── video path ──────────────────────────────────────────────────────
    def video_2d(self, frames: Tensor) -> Dict[str, Any]:
        return self.video.run_2d(frames)

    def video_3d(self, seed: int = 0, n_frames: Optional[int] = None,
                 grid: Optional[int] = None) -> Dict[str, Any]:
        if n_frames:
            self.video.cfg.n_frames = n_frames
        u, sigma = self.make_field(grid or max(12, self.cfg.grid3d // 2),
                                   seed=seed, steps=6)
        self.video.cfg.dx = self.cfg.dx
        return self.video.run_3d(u, sigma, solver="ch")

    def get_status(self) -> Dict[str, Any]:
        return {
            "fractal": self.calibration.name if self.calibration else self.cfg.fractal,
            "d_f": float(self.amr.d_f),
            "resolution": self.cfg.resolution.value,
            "ocio_loaded": self.ocio_loader is not None,
            "params": sum(p.numel() for p in self.parameters()),
            "trainable": sum(p.numel() for p in self.parameters() if p.requires_grad),
        }


