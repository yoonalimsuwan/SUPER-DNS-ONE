class BitmapRealismRenderer(nn.Module):
    """
    [D] Vector geometry + PFC/CH procedural micro-texture fill.

    The vector edge field v from VectorGradeBitmapEngine defines REGIONS.
    Each region is filled not with a flat colour but with a phase-field
    micro-texture (PFC crystal grain / CH spinodal / thin-film dewetting),
    modulated by the carpet measure. Result: resolution-independent geometry
    with bitmap-grade material richness.

    AMR super-sampling at the edges removes the stairstepping that makes
    naive vector output look "broken" at high zoom.
    """

    def __init__(self, pfc_r: float = -0.5, ch_epsilon: float = 1.5,
                 supersample: int = 2, texture_gain: float = 0.18):
        super().__init__()
        self.supersample = int(max(1, supersample))
        cfg_pfc = CahnHilliardConfig(dx=1.0, epsilon=ch_epsilon, dt=1e-6,
                                     pfc_r=pfc_r, laplacian="conv3d",
                                     scheme="imex", dtype=torch.float32)
        self.pfc = PhaseFieldCrystal3D(cfg_pfc)
        cfg_ch = CahnHilliardConfig(dx=1.0, epsilon=ch_epsilon, dt=1e-5,
                                    laplacian="conv3d", scheme="imex",
                                    dtype=torch.float32)
        self.ch = StructuralCahnHilliard3D(cfg_ch)
        self.log_gain = nn.Parameter(torch.tensor(math.log(texture_gain)))

    def micro_texture(self, shape: Tuple[int, ...], style: str = "pfc",
                      steps: int = 12, seed: int = 0,
                      sigma: Optional[Tensor] = None) -> Tensor:
        """Generate a procedural micro-texture field in ~[-1,1]."""
        g = torch.Generator(device="cpu").manual_seed(seed)
        if len(shape) == 2:
            shape3 = (shape[0], shape[1], 1)
        else:
            shape3 = tuple(shape)
        u = (torch.rand(*shape3, generator=g, dtype=torch.float32) * 0.4 - 0.2)
        u = u.to(next(self.parameters()).device if any(True for _ in self.parameters())
                 else u.device)
        if sigma is None:
            sigma = torch.ones_like(u)
        for _ in range(steps):
            u = (self.pfc.step(u, sigma) if style == "pfc"
                 else self.ch.step(u, sigma))
        u = u - u.mean()
        return u / (u.std() + 1e-8)

    def forward(self, base: Tensor, v: Tensor,
                style: str = "pfc", steps: int = 12,
                seed: int = 0) -> Dict[str, Tensor]:
        """
        base: (B,3,H,W) vector-grade reconstruction u.
        v:    (B,1,H,W) AT edge field.
        Returns the materialised "bitmap-realistic" raster.
        """
        H, W = base.shape[-2:]
        ss = self.supersample
        if ss > 1:
            base_hi = F.interpolate(base, size=(H * ss, W * ss),
                                    mode="bicubic", align_corners=False)
            v_hi = F.interpolate(v, size=(H * ss, W * ss),
                                 mode="bicubic", align_corners=False)
        else:
            base_hi, v_hi = base, v

        tex = self.micro_texture((base_hi.shape[-2], base_hi.shape[-1]),
                                 style=style, steps=steps, seed=seed)
        tex = tex.to(base_hi.device, base_hi.dtype)
        gain = self.log_gain.exp()

        # texture lives INSIDE regions, suppressed on edges (keeps contours crisp)
        interior = (v_hi > 0.9).to(base_hi.dtype)
        if tex.dim() == 2:
            tex = tex.unsqueeze(0).unsqueeze(0)
        elif tex.dim() == 3:
            tex = tex.unsqueeze(0)
        tex = tex[..., :base_hi.shape[-2], :base_hi.shape[-1]]
        if tex.shape[-2] != base_hi.shape[-2] or tex.shape[-1] != base_hi.shape[-1]:
            tex = F.interpolate(tex, size=base_hi.shape[-2:], mode="bilinear",
                                align_corners=False)

        shaded = base_hi + gain * tex * interior
        # luminance-preserving: keep the vector colour identity
        lum0 = base_hi.mean(1, keepdim=True)
        lum1 = shaded.mean(1, keepdim=True)
        shaded = shaded + (lum0 - lum1) * 0.5

        out = shaded.clamp(0, 1)
        return {"raster": out, "micro_texture": tex,
                "interior_mask": interior, "supersample": ss,
                "resolution": (int(out.shape[-1]), int(out.shape[-2]))}

