class NonPCFCalibrator:
    """
    [D/O] Calibrate carpet-style AMR exponents for ANY non-PCF fractal.

      d_f  from box counting            N(eps) ~ eps^{-d_f}
      d_w  from random-walk MSD         <r^2(t)> ~ t^{2/d_w}
      rho_eff = 3^{d_w}/8               (carpet-normalised resistance)
      alpha   = 2/d_w                   (Caputo order)
      d_s     = 2 d_f/d_w               (spectral dimension)

    HONEST [O]: this is EXPONENT MATCHING. It does NOT prove that the
    carpet's Mosco closure (Carpet-19 Thm 2 / Thm 10) transfers to the
    target set. For the carpet itself, (I1)-(I4) follow from KZ Thms 5.4,
    7.2, 7.16, 7.19 + BBKT Thm 1.2 + Hino Thm 5.3. For every other
    non-PCF set, (I1)-(I4) ARE the unproved content. Validate against an
    analytic reference before production use.
    """

    # ── box counting ────────────────────────────────────────────────────
    @staticmethod
    def box_counting(mask: np.ndarray,
                     scales: Optional[List[int]] = None
                     ) -> Tuple[float, float, List[Tuple[int, int]]]:
        nd = mask.ndim
        L = min(mask.shape)
        if scales is None:
            scales = [2 ** k for k in range(0, int(math.log2(max(L, 2))) + 1)]
            scales = [s for s in scales if 1 <= s <= max(L // 2, 1)]
        pts = []
        for s in scales:
            crops = tuple(slice(0, (d // s) * s) for d in mask.shape)
            m = mask[crops]
            if m.size == 0:
                continue
            shape = tuple(d // s for d in m.shape)
            blocks = m.reshape(sum(((sh, s) for sh in shape), ()))
            axes = tuple(range(1, 2 * nd, 2))
            n = int(blocks.any(axis=axes).sum())
            if n > 0:
                pts.append((s, n))
        if len(pts) < 3:
            return float("nan"), 0.0, pts
        x = np.log(1.0 / np.array([p[0] for p in pts], dtype=float))
        y = np.log(np.array([p[1] for p in pts], dtype=float))
        slope, intercept = np.polyfit(x, y, 1)
        pred = slope * x + intercept
        ss_res = float(((y - pred) ** 2).sum())
        ss_tot = float(((y - y.mean()) ** 2).sum()) + 1e-12
        return float(slope), 1.0 - ss_res / ss_tot, pts

    # ── random walk MSD ─────────────────────────────────────────────────
    @staticmethod
    def walk_msd(mask: np.ndarray, n_walks: int = 512, n_steps: int = 400,
                 seed: int = 0) -> Tuple[np.ndarray, np.ndarray]:
        """
        Random walk confined to occupied cells. Returns (times, msd).
        d_w from  <r^2> ~ t^{2/d_w}.
        """
        rng = np.random.default_rng(seed)
        occ = np.argwhere(mask)
        if len(occ) < 8:
            return np.array([]), np.array([])
        occ_set = set(map(tuple, occ.tolist()))
        nd = mask.ndim
        starts = occ[rng.choice(len(occ), size=min(n_walks, len(occ)), replace=False)]
        pos = starts.astype(np.int64).copy()
        origin = pos.astype(float).copy()
        times, msd = [0.0], [0.0]
        for t in range(1, n_steps + 1):
            axis = rng.integers(0, nd, size=len(pos))
            sign = rng.choice([-1, 1], size=len(pos))
            cand = pos.copy()
            cand[np.arange(len(pos)), axis] += sign
            ok = np.array([tuple(c) in occ_set for c in cand])
            pos[ok] = cand[ok]
            d2 = ((pos.astype(float) - origin) ** 2).sum(1)
            times.append(float(t))
            msd.append(float(d2.mean()))
        return np.array(times), np.array(msd)

    @staticmethod
    def fit_dw(times: np.ndarray, msd: np.ndarray,
               t_lo: int = 4, t_hi_frac: float = 0.6
               ) -> Tuple[float, float]:
        if len(times) < 10:
            return float("nan"), 0.0
        hi = max(t_lo + 2, int(len(times) * t_hi_frac))
        t = times[t_lo:hi]
        m = msd[t_lo:hi]
        ok = (t > 0) & (m > 0)
        if ok.sum() < 5:
            return float("nan"), 0.0
        x, y = np.log(t[ok]), np.log(m[ok])
        slope, intercept = np.polyfit(x, y, 1)
        pred = slope * x + intercept
        ss_res = float(((y - pred) ** 2).sum())
        ss_tot = float(((y - y.mean()) ** 2).sum()) + 1e-12
        dw = 2.0 / max(slope, 1e-9)
        return float(dw), 1.0 - ss_res / ss_tot

    # ── full calibration ────────────────────────────────────────────────
    def calibrate(self, spec: FractalSpec, level: int = 4,
                  n_walks: int = 384, n_steps: int = 300,
                  seed: int = 0) -> FractalCalibration:
        mask = FractalRegistry.mask(spec, level)
        df, r2f, _ = self.box_counting(mask)
        disconnected = (spec.name == "cantor_dust")
        if disconnected:
            dw, r2w = 2.0, 0.0     # no connected walker; report the trivial value
        else:
            times, msd = self.walk_msd(mask, n_walks, n_steps, seed)
            dw, r2w = self.fit_dw(times, msd)
        if not np.isfinite(dw) or dw <= 0:
            dw = 2.0
        rho = 3.0 ** dw / 8.0
        alpha = float(np.clip(2.0 / dw, 1e-3, 1 - 1e-3))
        ds = 2.0 * df / dw if np.isfinite(df) else float("nan")
        theo = spec.theoretical_df
        abs_err = abs(df - theo) if theo is not None else None
        return FractalCalibration(
            name=spec.name,
            d_f_measured=df, d_f_theoretical=theo, d_f_r2=r2f, d_f_abs_err=abs_err,
            d_w_measured=dw, d_w_r2=r2w, rho_eff=rho,
            alpha_caputo=alpha, d_s=ds,
            is_pcf=spec.is_pcf,
            closure_transferred=False,
            label=("[C] anchor: closure from KZ/BBKT/Hino"
                   if spec.name == "sierpinski_carpet" else
                   "[O] exponent-matched transplant; closure NOT proven"),
            notes=spec.notes,
        )

    def calibrate_all(self, level: int = 4,
                      n_walks: int = 256, n_steps: int = 240
                      ) -> Dict[str, FractalCalibration]:
        out = {}
        for name, spec in FractalRegistry.all_specs().items():
            try:
                out[name] = self.calibrate(spec, level, n_walks, n_steps)
            except Exception as e:                       # pragma: no cover
                logger.warning("calibration failed for %s: %s", name, e)
        return out


