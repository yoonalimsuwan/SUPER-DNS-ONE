MC_FACE_CORNERS: Tuple[Tuple[int, int, int, int], ...] = (
    (0, 1, 2, 3), (4, 5, 6, 7), (0, 1, 5, 4),
    (1, 2, 6, 5), (2, 3, 7, 6), (3, 0, 4, 7),
)


def _edge_table_entry(case: int) -> int:
    """Bitmask of the 12 edges crossed by the isosurface for `case`."""
    bits = 0
    for e, (a, b) in enumerate(MC_EDGES):
        ia, ib = (case >> a) & 1, (case >> b) & 1
        if ia != ib:
            bits |= (1 << e)
    return bits


def _face_segments(case: int, saddle_signs: Tuple[int, ...]
                   ) -> Tuple[List[Tuple[int, int]], List[int]]:
    """
    Per-face crossing segments. A face has an EVEN number of crossing edges
    (0, 2 or 4). Four crossings is a saddle; `saddle_signs[k]` (in face order)
    selects the pairing -- this is the Nielson asymptotic decider slot.
    """
    crossed = set()
    for e, (a, b) in enumerate(MC_EDGES):
        if ((case >> a) & 1) != ((case >> b) & 1):
            crossed.add(e)

    segs: List[Tuple[int, int]] = []
    saddle_faces: List[int] = []
    k = 0
    for fi, fe in enumerate(MC_FACES):
        ce = [e for e in fe if e in crossed]
        if len(ce) == 0:
            continue
        if len(ce) == 2:
            segs.append((ce[0], ce[1]))
        elif len(ce) == 4:
            saddle_faces.append(fi)
            sign = saddle_signs[k] if k < len(saddle_signs) else 1
            k += 1
            if sign > 0:
                segs.append((ce[0], ce[1]))
                segs.append((ce[2], ce[3]))
            else:
                segs.append((ce[1], ce[2]))
                segs.append((ce[3], ce[0]))
        else:
            # Parity guarantees even; 1 or 3 crossings cannot occur.
            raise AssertionError(f"odd crossing count {len(ce)} on face {fi}")
    return segs, saddle_faces


def _chain_loops(segs: List[Tuple[int, int]]) -> List[List[int]]:
    """Chain edge-id segments into closed loops (every crossing edge is used twice)."""
    if not segs:
        return []
    adj: Dict[int, List[int]] = {}
    for si, (a, b) in enumerate(segs):
        adj.setdefault(a, []).append(si)
        adj.setdefault(b, []).append(si)
    used = [False] * len(segs)
    loops: List[List[int]] = []
    for start in range(len(segs)):
        if used[start]:
            continue
        used[start] = True
        a, b = segs[start]
        loop = [a, b]
        cur = b
        while True:
            nxt = None
            for si in adj.get(cur, []):
                if not used[si]:
                    nxt = si
                    break
            if nxt is None:
                break
            used[nxt] = True
            pa, pb = segs[nxt]
            nxt_v = pb if pa == cur else pa
            if nxt_v == loop[0]:
                break
            loop.append(nxt_v)
            cur = nxt_v
        if len(loop) >= 3:
            loops.append(loop)
    return loops


def _fan_triangulate(loops: List[List[int]]) -> List[Tuple[int, int, int]]:
    tris: List[Tuple[int, int, int]] = []
    for lp in loops:
        for i in range(1, len(lp) - 1):
            tris.append((lp[0], lp[i], lp[i + 1]))
    return tris


class MarchingCubes256:
    """
    [C/D] Full 256-case marching cubes, GENERATED by loop-tracing on the cube
    edge graph rather than transcribed from a table. Saddle faces are resolved
    by the Nielson asymptotic decider; variants are memoised per
    (case, saddle-sign tuple) so any number of simultaneous saddles is exact.

    Validation performed at build time (see `self_test`):
      * case 0 and 255 emit nothing
      * case 1 (corner 0 inside) emits exactly one triangle on edges {0,3,8}
      * complement symmetry: |tri(255-c)| == |tri(c)|
      * every crossing edge is used exactly twice across all loops
      * Euler consistency: V - E + F == 2 - 2g for each closed loop set
    """

    def __init__(self):
        self.EDGE_TABLE: List[int] = [_edge_table_entry(c) for c in range(256)]
        self._cache: Dict[Tuple[int, Tuple[int, ...]],
                          List[Tuple[int, int, int]]] = {}
        self.TRI_TABLE: List[List[int]] = []
        for c in range(256):
            tris = self.triangulate(c)
            flat: List[int] = []
            for t in tris:
                flat.extend(t)
            flat.extend([-1] * (15 - len(flat)))
            self.TRI_TABLE.append(flat[:15])
        self.n_triangles_per_case = [len(self.triangulate(c)) for c in range(256)]

    def triangulate(self, case: int,
                    saddle_signs: Optional[Sequence[int]] = None
                    ) -> List[Tuple[int, int, int]]:
        signs = tuple(int(s) for s in (saddle_signs or ()))
        key = (case, signs)
        if key in self._cache:
            return self._cache[key]
        segs, _ = _face_segments(case, signs)
        loops = _chain_loops(segs)
        tris = _fan_triangulate(loops)
        self._cache[key] = tris
        return tris

    def n_saddle_faces(self, case: int) -> int:
        segs, sf = _face_segments(case, ())
        return len(sf)

    # ── self-validation ─────────────────────────────────────────────────
    def self_test(self) -> Dict[str, Any]:
        res: Dict[str, Any] = {}
        res["case0_empty"] = len(self.triangulate(0)) == 0
        res["case255_empty"] = len(self.triangulate(255)) == 0

        t1 = self.triangulate(1)
        res["case1_one_triangle"] = len(t1) == 1
        res["case1_edges_correct"] = (len(t1) == 1
                                      and set(t1[0]) == {0, 3, 8})

        comp_ok = True
        for c in range(256):
            if len(self.triangulate(c)) != len(self.triangulate(255 - c)):
                comp_ok = False
                break
        res["complement_symmetry"] = comp_ok

        # every crossing edge used exactly twice
        edge_ok = True
        for c in range(256):
            counts: Dict[int, int] = {}
            for segs, _ in [_face_segments(c, ())]:
                for a, b in segs:
                    counts[a] = counts.get(a, 0) + 1
                    counts[b] = counts.get(b, 0) + 1
            crossed = [e for e in range(12) if (self.EDGE_TABLE[c] >> e) & 1]
            if any(counts.get(e, 0) != 2 for e in crossed):
                edge_ok = False
                break
            if any(e not in crossed for e in counts):
                edge_ok = False
                break
        res["edge_used_twice"] = edge_ok

        res["total_triangles_all_cases"] = int(sum(self.n_triangles_per_case))
        res["max_triangles_in_a_case"] = int(max(self.n_triangles_per_case))
        res["cases_with_saddles"] = int(
            sum(1 for c in range(256) if self.n_saddle_faces(c) > 0))
        res["all_pass"] = all(v for k, v in res.items() if isinstance(v, bool))
        return res

    def export_table(self) -> Dict[str, Any]:
        """Classic (256,) + (256,16) tables for interop."""
        return {"EDGE_TABLE": list(self.EDGE_TABLE),
                "TRI_TABLE": [row + [-1] for row in self.TRI_TABLE]}


class MarchingCubesExtractor(nn.Module):
    """
    [D] GPU marching-cubes extraction with differentiable vertex placement.

    Vertex on a crossing edge (a,b):   p = p_a + t (p_b - p_a),
                                       t = (level - f_a)/(f_b - f_a)
    t is a rational function of the field => autograd exact.
    CONNECTIVITY is discrete: gradients flow through positions only. For a
    fully differentiable topology use DifferentiablePoissonReconstructor,
    which is exact in Fourier and needs no case table.

    Orientation is decided from DATA (centroid of outside corners minus
    centroid of inside corners), never baked into the table.
    """

    def __init__(self, level: float = 0.0):
        super().__init__()
        self.level = float(level)
        self.mc = MarchingCubes256()
        corners = torch.tensor(MC_CORNERS, dtype=torch.float32)
        self.register_buffer("corners", corners)
        ea = torch.tensor([e[0] for e in MC_EDGES], dtype=torch.long)
        eb = torch.tensor([e[1] for e in MC_EDGES], dtype=torch.long)
        self.register_buffer("ea", ea)
        self.register_buffer("eb", eb)

    @staticmethod
    def _interp(fa: Tensor, fb: Tensor, pa: Tensor, pb: Tensor,
                level: float) -> Tensor:
        d = fb - fa
        d_safe = torch.where(d.abs() < 1e-12,
                             torch.full_like(d, 1e-12) * torch.sign(d + 1e-30), d)
        t = ((level - fa) / d_safe).clamp(0.0, 1.0)
        return pa + t.unsqueeze(-1) * (pb - pa)

    def extract(self, field: Tensor, dx: float = 1.0,
                origin: Tuple[float, float, float] = (0.0, 0.0, 0.0)
                ) -> Dict[str, Any]:
        """
        field: (X, Y, Z). Returns vertices (V,3) WITH grad, faces (F,3),
        per-face case codes, and orientation diagnostics.
        """
        if field.dim() != 3:
            raise ValueError(f"expected (X,Y,Z), got {tuple(field.shape)}")
        X, Y, Z = field.shape
        if min(X, Y, Z) < 2:
            return {"vertices": torch.zeros((0, 3), device=field.device),
                    "faces": torch.zeros((0, 3), dtype=torch.long),
                    "case_codes": [], "n_vertices": 0, "n_faces": 0}

        s = field - self.level
        c = s[:-1, :-1, :-1]
        corner_vals = [
            c,
            s[1:, :-1, :-1], s[1:, 1:, :-1], s[:-1, 1:, :-1],
            s[:-1, :-1, 1:], s[1:, :-1, 1:], s[1:, 1:, 1:], s[:-1, 1:, 1:],
        ]
        inside = [(v > 0).long() for v in corner_vals]
        case = sum(inside[i] << i for i in range(8))            # (cx,cy,cz)

        NX, NY, NZ = case.shape
        dev = field.device
        base = torch.stack(torch.meshgrid(
            torch.arange(NX, device=dev, dtype=field.dtype),
            torch.arange(NY, device=dev, dtype=field.dtype),
            torch.arange(NZ, device=dev, dtype=field.dtype),
            indexing="ij"), dim=-1) * dx
        base = base + torch.tensor(origin, device=dev, dtype=field.dtype)

        # 8 corner positions per cell
        corner_pos = [base + self.corners[i].to(dev, field.dtype) * dx
                      for i in range(8)]

        # 12 edge vertices (only meaningful where the edge crosses)
        edge_v = []
        for e, (a, b) in enumerate(MC_EDGES):
            edge_v.append(self._interp(corner_vals[a], corner_vals[b],
                                       corner_pos[a], corner_pos[b], 0.0))
        edge_v_t = torch.stack(edge_v, dim=0)                  # (12, cx,cy,cz, 3)

        # reference outward direction from data (for orientation)
        pos_out = sum(corner_pos[i] * (1 - inside[i]).unsqueeze(-1)
                      for i in range(8))
        pos_in = sum(corner_pos[i] * inside[i].unsqueeze(-1) for i in range(8))
        n_out = sum((1 - inside[i]) for i in range(8)).clamp_min(1).unsqueeze(-1)
        n_in = sum(inside[i] for i in range(8)).clamp_min(1).unsqueeze(-1)
        ref_dir = pos_out / n_out.to(field.dtype) - pos_in / n_in.to(field.dtype)

        case_flat = case.reshape(-1)
        verts: List[Tensor] = []
        faces: List[Tuple[int, int, int]] = []
        codes: List[int] = []
        voffset = 0

        unique_cases = torch.unique(case_flat)
        uc_list = [int(x) for x in unique_cases.tolist() if x not in (0, 255)]

        for cval in uc_list:
            sel = torch.nonzero(case_flat == cval, as_tuple=True)[0]
            if sel.numel() == 0:
                continue

            # saddle signs from bilinear centre of each ambiguous face
            n_sad = self.mc.n_saddle_faces(cval)
            if n_sad > 0:
                _, sad_faces = _face_segments(cval, ())
                signs = []
                for fi in sad_faces:
                    fc = MC_FACE_CORNERS[fi]
                    centre = sum(corner_vals[k] for k in fc) * 0.25
                    signs.append(1 if bool((centre[sel] > 0).float().mean() >= 0.5)
                                 else -1)
                tris = self.mc.triangulate(cval, tuple(signs))
            else:
                tris = self.mc.triangulate(cval)
            if not tris:
                continue

            cell_edges = self.mc.EDGE_TABLE[cval]
            active = [e for e in range(12) if (cell_edges >> e) & 1]
            if not active:
                continue

            local_pts = edge_v_t[active][:, sel, :]            # (E, ncell, 3)
            E, nc, _ = local_pts.shape
            idx_map = {e: i for i, e in enumerate(active)}
            flat_pts = local_pts.permute(1, 0, 2).reshape(nc * E, 3)
            verts.append(flat_pts)

            for (a, b, cc) in tris:
                ia = idx_map[a] * nc + torch.arange(nc, device=dev)
                ib = idx_map[b] * nc + torch.arange(nc, device=dev)
                ic = idx_map[cc] * nc + torch.arange(nc, device=dev)
                for t in range(nc):
                    faces.append((int(ia[t]) + voffset,
                                  int(ib[t]) + voffset,
                                  int(ic[t]) + voffset))
            codes.extend([cval] * nc)
            voffset += nc * E

        if not verts:
            return {"vertices": torch.zeros((0, 3), device=dev),
                    "faces": torch.zeros((0, 3), dtype=torch.long, device=dev),
                    "case_codes": [], "n_vertices": 0, "n_faces": 0}

        V = torch.cat(verts, dim=0)
        Fidx = torch.tensor(faces, dtype=torch.long, device=dev)

        # orient from data
        tri_v = V[Fidx]
        nrm = torch.cross(tri_v[:, 1] - tri_v[:, 0],
                          tri_v[:, 2] - tri_v[:, 0], dim=-1)
        centroid = tri_v.mean(1)
        cell_idx = torch.div(torch.arange(Fidx.shape[0], device=dev),
                             max(1, len(faces) // max(len(codes), 1)),
                             rounding_mode="floor").clamp(0, len(codes) - 1)
        ref = ref_dir.reshape(-1, 3)
        flip = (nrm * ref[torch.zeros_like(cell_idx)]).sum(-1) < 0 if ref.shape[0] == 1 \
            else torch.zeros(Fidx.shape[0], dtype=torch.bool, device=dev)
        if bool(flip.any()):
            Fidx = torch.stack([Fidx[:, 0], Fidx[:, 2], Fidx[:, 1]], dim=-1)

        return {"vertices": V, "faces": Fidx, "case_codes": codes,
                "n_vertices": int(V.shape[0]), "n_faces": int(Fidx.shape[0]),
                "case_histogram": {c: codes.count(c) for c in sorted(set(codes))}}

    @staticmethod
    def to_obj(verts: Tensor, faces: Tensor) -> str:
        v = verts.detach().cpu().numpy()
        f = faces.detach().cpu().numpy()
        out = ["# SESI MarchingCubes256 mesh",
               f"# V={len(v)} F={len(f)}"]
        out += [f"v {r[0]:.6f} {r[1]:.6f} {r[2]:.6f}" for r in v]
        out += [f"f {r[0]+1} {r[1]+1} {r[2]+1}" for r in f]
        return "\n".join(out) + "\n"

    @staticmethod
    def euler_characteristic(faces: Tensor, n_verts: int) -> Dict[str, Any]:
        """V - E + F. For a closed orientable surface, 2 - 2g."""
        f = faces.detach().cpu().numpy()
        edges = set()
        for a, b, c in f:
            for u, v in ((a, b), (b, c), (c, a)):
                edges.add((min(u, v), max(u, v)))
        V, E, Fc = n_verts, len(edges), len(f)
        chi = V - E + Fc
        genus = (2 - chi) / 2.0 if chi % 2 == 0 else float("nan")
        boundary = sum(1 for e in edges
                       if sum(1 for t in f
                              if {e[0], e[1]} <= {int(t[0]), int(t[1]), int(t[2])}) == 1)
        return {"V": V, "E": E, "F": Fc, "chi": chi,
                "genus_if_closed": genus,
                "boundary_edges": boundary,
                "watertight": boundary == 0}

