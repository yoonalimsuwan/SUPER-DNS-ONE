    @staticmethod
    def mask(spec: FractalSpec, level: int) -> np.ndarray:
        """Exact recursive occupancy mask."""
        dim = 3 if spec.name == "menger_sponge" else 2
        m = np.ones([1] * dim, dtype=bool)
        for _ in range(level):
            shape = [spec.base] * dim
            pattern = np.zeros(shape, dtype=bool)
            flat = pattern.reshape(-1)
            for idx in spec.keep:
                if idx < flat.size:
                    flat[idx] = True
            out = np.zeros([s * spec.base for s in m.shape], dtype=bool)
            if dim == 2:
                for i in range(spec.base):
                    for j in range(spec.base):
                        if pattern[i, j]:
                            out[i * m.shape[0]:(i + 1) * m.shape[0],
                                j * m.shape[1]:(j + 1) * m.shape[1]] = m
            else:
                for i in range(spec.base):
                    for j in range(spec.base):
                        for k in range(spec.base):
                            if pattern[i, j, k]:
                                out[i * m.shape[0]:(i + 1) * m.shape[0],
                                    j * m.shape[1]:(j + 1) * m.shape[1],
                                    k * m.shape[2]:(k + 1) * m.shape[2]] = m
            m = out
        return m


