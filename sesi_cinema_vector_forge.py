class CharTokenizer:
    """Deterministic byte-level tokenizer. No external vocab required."""
    PAD, BOS, EOS, UNK = 0, 1, 2, 3

    def __init__(self, max_len: int = 128):
        self.max_len = max_len

    def encode(self, text: str) -> List[int]:
        ids = [self.BOS] + [min(255, ord(c)) + 4 for c in text[: self.max_len - 2]] \
              + [self.EOS]
        ids += [self.PAD] * (self.max_len - len(ids))
        return ids[: self.max_len]

    def encode_batch(self, texts: Sequence[str]) -> Tensor:
        return torch.tensor([self.encode(t) for t in texts], dtype=torch.long)

    @property
    def vocab_size(self) -> int:
        return 260


@dataclass
class PromptShapeConfig:
    d_model: int = 256
    n_heads: int = 8
    n_layers: int = 4
    grid: int = 16                 # latent field is grid x grid x grid
    max_len: int = 128
    world_model_dim: int = 256
    world_model_steps: int = 6


class PromptShapeTransformer(nn.Module):
    """
    [D] Prompt -> (initial phase field u0, sigma field, PFC r, texture style).

    HONEST: ships with RANDOM INITIALISATION. Without a trained
    (prompt, target-shape) corpus this maps text to noise-conditioned noise.
    The architecture is production-shaped; the weights are not.
    """

    def __init__(self, cfg: Optional[PromptShapeConfig] = None):
        super().__init__()
        self.cfg = cfg or PromptShapeConfig()
        self.tok = CharTokenizer(self.cfg.max_len)
        self.embed = nn.Embedding(self.tok.vocab_size, self.cfg.d_model,
                                  padding_idx=CharTokenizer.PAD)
        self.pos = nn.Parameter(torch.randn(1, self.cfg.max_len,
                                            self.cfg.d_model) * 0.02)
        layer = nn.TransformerEncoderLayer(
            d_model=self.cfg.d_model, nhead=self.cfg.n_heads,
            dim_feedforward=self.cfg.d_model * 4, batch_first=True,
            activation="gelu")
        self.enc = nn.TransformerEncoder(layer, num_layers=self.cfg.n_layers)

        n_cell = self.cfg.grid ** 3
        self.field_head = nn.Linear(self.cfg.d_model, n_cell)
        self.sigma_head = nn.Linear(self.cfg.d_model, n_cell)
        self.scalar_head = nn.Sequential(
            nn.Linear(self.cfg.d_model, 64), nn.GELU(), nn.Linear(64, 5))
        self.style_embed = nn.Embedding(8, 64)

    def forward(self, texts: Sequence[str]) -> Dict[str, Tensor]:
        ids = self.tok.encode_batch(list(texts)).to(
            next(self.parameters()).device)
        mask = ids == CharTokenizer.PAD
        x = self.embed(ids) + self.pos[:, : ids.shape[1]]
        h = self.enc(x, src_key_padding_mask=mask)
        pooled = h.mean(1)

        n_cell = self.cfg.grid ** 3
        u0 = torch.tanh(self.field_head(pooled)).reshape(-1, self.cfg.grid,
                                                         self.cfg.grid, self.cfg.grid)
        sigma = F.softplus(self.sigma_head(pooled)).reshape(
            -1, self.cfg.grid, self.cfg.grid, self.cfg.grid) + 0.1
        sc = self.scalar_head(pooled)
        style_logits = self.style_embed(torch.arange(8, device=pooled.device)
                                        ).mean(0, keepdim=True).expand(pooled.shape[0], -1) \
            @ pooled.unsqueeze(-1)
        return {
            "u0": u0 * 0.2,
            "sigma": sigma,
            "pfc_r": torch.tanh(sc[:, 0]) * 1.5,
            "ch_epsilon": 1.0 + F.softplus(sc[:, 1]),
            "texture_gain": torch.sigmoid(sc[:, 2]),
            "temporal_rate": torch.sigmoid(sc[:, 3]),
            "vector_grade_target": torch.sigmoid(sc[:, 4]),
            "style_logits": style_logits.squeeze(-1),
            "prompt_embedding": pooled,
        }


class ShapeWorldModel(nn.Module):
    """
    [C/D] Latent world model (Ha & Schmidhuber pattern) over the phase field.

    Encodes the field, rolls a latent dynamics model forward, decodes an
    imagined future field. Lets the system PREVIEW a prompt-conditioned shape
    evolution without running the full CH/PFC solve -- and gives a cheap
    differentiable surrogate for gradient-based prompt optimisation.

    HONEST: the surrogate is only as good as its training data. It is a
    PREVIEW, not a substitute for the embedded solver.
    """

    def __init__(self, cfg: Optional[PromptShapeConfig] = None):
        super().__init__()
        self.cfg = cfg or PromptShapeConfig()
        n_cell = self.cfg.grid ** 3
        d = self.cfg.world_model_dim
        self.enc = nn.Sequential(nn.Linear(n_cell, 512), nn.GELU(),
                                 nn.Linear(512, d * 2))
        self.dyn = nn.GRUCell(d, d)
        self.dec = nn.Sequential(nn.Linear(d, 512), nn.GELU(),
                                 nn.Linear(512, n_cell))
        self.reward = nn.Sequential(nn.Linear(d, 64), nn.GELU(),
                                    nn.Linear(64, 2))

    def encode(self, u: Tensor) -> Tuple[Tensor, Tensor]:
        flat = u.reshape(u.shape[0], -1)
        mu, lv = self.enc(flat).chunk(2, -1)
        return mu, lv.clamp(-8, 8)

    def reparam(self, mu, lv):
        return mu + torch.randn_like(mu) * (0.5 * lv).exp()

    def imagine(self, z: Tensor, steps: Optional[int] = None) -> Tensor:
        steps = steps or self.cfg.world_model_steps
        traj = [z]
        for _ in range(steps):
            z = self.dyn(z, z)
            traj.append(z)
        return torch.stack(traj, 1)

    def forward(self, u: Tensor, steps: Optional[int] = None) -> Dict[str, Tensor]:
        mu, lv = self.encode(u)
        z = self.reparam(mu, lv)
        traj = self.imagine(z, steps)
        B, S, D = traj.shape
        decoded = self.dec(traj.reshape(B * S, D)).reshape(
            B, S, self.cfg.grid, self.cfg.grid, self.cfg.grid)
        rw = self.reward(traj[:, -1])
        return {"trajectory": traj, "imagined_fields": decoded,
                "mu": mu, "logvar": lv,
                "kl": 0.5 * (mu.pow(2) + lv.exp() - 1 - lv).sum(-1),
                "predicted_reward": torch.tanh(rw[:, 0]),
                "predicted_vector_grade_index": torch.sigmoid(rw[:, 1])}


