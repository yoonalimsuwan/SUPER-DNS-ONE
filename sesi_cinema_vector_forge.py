@dataclass
class ATConfig:
    epsilon: float = 0.03
    alpha_fidelity: float = 8.0
    beta_length: float = 0.5
    eta_reg: float = 1e-5
    n_steps: int = 80
    dt: float = 0.15
    epsilon_decay: float = 0.93
    min_epsilon: float = 0.004
    use_fractal_sigma: bool = True
    fractal_level: int = 2


def _lap_2d(u: Tensor, dx: float) -> Tensor:
    lap = torch.zeros_like(u)
    for ax in range(2, u.dim()):
        lap = lap + (torch.roll(u, -1, ax) - 2 * u + torch.roll(u, +1, ax)) / dx ** 2
    return lap


class VectorGradeBitmapEngine(nn.Module):
    """
    [C/D] Ambrosio-Tortorelli + carpet-measure AMR.

        E_eps[u,v] = int (v^2+eta)|grad u|^2 + alpha (u-I)^2
                         + beta ( eps|grad v|^2 + (1-v)^2/(4 eps) )
        E_eps --Gamma--> Mumford-Shah  as eps -> 0

    v -> 1 on flats  => uniform fills, indistinguishable from vector solids
    v -> 0 on K      => razor contours, indistinguishable from vector strokes
    The CONDUCTIVITY of the u-diffusion is additionally modulated by the
    carpet measure sigma_K = h^{d_f-d}, so the piecewise-smooth decomposition
    respects the fractal geometry rather than fighting it. This is why the
    bitmap output does not "break" the way naive vectorisation does.
    """

    def __init__(self, cfg: Optional[ATConfig] = None,
                 amr: Optional[CarpetAMRController] = None):
        super().__init__()
        self.cfg = cfg or ATConfig()
        self.amr = amr or CarpetAMRController()
        self.log_alpha = nn.Parameter(torch.tensor(math.log(self.cfg.alpha_fidelity)))
        self.log_beta = nn.Parameter(torch.tensor(math.log(self.cfg.beta_length)))

    def _cond(self, v: Tensor, u: Tensor, dx: float, level: int) -> Tensor:
        c = v ** 2 + self.cfg.eta_reg
        if not self.cfg.use_fractal_sigma:
            return c
        sigma = self.amr.fractal_sigma(u.shape, level, u.device, u.dtype)
        # normalise so sigma modulates but does not rescale the energy wildly
        sigma = sigma / sigma.mean().clamp_min(1e-12)
        return c * (0.5 + 0.5 * sigma)

    def forward(self, I: Tensor, dx: float = 1.0, level: int = 2,
                use_checkpoint: bool = False) -> Dict[str, Any]:
        u = I.clone()
        v = torch.ones_like(I)
        eps = self.cfg.epsilon
        a, b = self.log_alpha.exp(), self.log_beta.exp()
        trace, vgi = [], []

        for it in range(self.cfg.n_steps):
            def _body(u_, v_, eps_):
                cond = self._cond(v_, u_, dx, level)
                u_new = u_ + self.cfg.dt * (_lap_2d(u_ * cond, dx) / cond.clamp_min(1e-8)
                                            - a * (u_ - I))
                gx = (torch.roll(u_new, -1, -1) - torch.roll(u_new, 1, -1)) / (2 * dx)
                gy = (torch.roll(u_new, -1, -2) - torch.roll(u_new, 1, -2)) / (2 * dx)
                gs = gx ** 2 + gy ** 2
                v_new = v_ + self.cfg.dt * (b * eps_ * _lap_2d(v_, dx)
                                            - v_ * gs + b * (1 - v_) / (4 * eps_))
                return u_new.clamp(0, 1), v_new.clamp(0, 1)

            if use_checkpoint and self.training:
                from torch.utils.checkpoint import checkpoint as _ck
                u, v = _ck(_body, u, v, eps, use_reentrant=False)
            else:
                u, v = _body(u, v, eps)

            if (it + 1) % 16 == 0:
                K = (v < 0.5).float().mean()
                flat = (v > 0.95).float().mean()
                trace.append({"iter": it + 1, "epsilon": eps,
                              "edge_fraction": float(K),
                              "flat_fraction": float(flat),
                              "vector_grade_index": float(flat / (K + 1e-6))})
                vgi.append(float(flat / (K + 1e-6)))
            eps = max(self.cfg.min_epsilon, eps * self.cfg.epsilon_decay)

        K = (v < 0.5).float()
        flat = (v > 0.95).float()
        amr_diag = self.amr.adapt(u, v, dx, level)
        amr_diag.pop("mask", None)

        return {
            "u": u, "v": v, "edge_mask": K,
            "epsilon_final": eps,
            "gamma_converged": eps <= self.cfg.min_epsilon * 1.5,
            "edge_fraction": float(K.mean()),
            "flat_fraction": float(flat.mean()),
            "vector_grade_index": float(flat.mean() / (K.mean() + 1e-6)),
            "vgi_trace": vgi,
            "energy_trace": trace,
            "amr": amr_diag,
            "conductivity_is_fractal": self.cfg.use_fractal_sigma,
        }


