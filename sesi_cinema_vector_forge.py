def structural_biharmonic_n(fld: Tensor, sigma: Tensor, n: int,
                            laplacian_fn: Callable) -> Tensor:
    """Delta_S^n u, recursively. n >= 1."""
    if n < 1:
        raise ValueError(f"n must be >= 1; got {n}")
    out = laplacian_fn(fld, sigma)
    for _ in range(n - 1):
        out = laplacian_fn(out, sigma)
    return out


