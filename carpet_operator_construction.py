# [T1] PRE-CARPET GRAPH + GRAPH LAPLACIAN  (real, computable)
# ═══════════════════════════════════════════════════════════════════════

class PreCarpetGraph:
    """
    Finite pre-carpet graph approximation at level m.

    The Sierpinski carpet is generated by subdividing a square into a
    (2k+1)x(2k+1) grid and removing the central cell, iterated. The
    standard carpet uses 3x3 with the center removed (8 retained cells).

    We build the vertex graph of the level-m pre-carpet and its adjacency,
    which is the substrate for the discrete Dirichlet energy
        E_m(u) = c_m * sum_{x~y} (u(x)-u(y))^2
    with resistance renormalization c_m (the rho^n gauge of the
    Consolidated Carpet paper).
    """

    def __init__(self, level: int = 2):
        self.level = level
        self.vertices, self.edges = self._build(level)
        self.index = {v: i for i, v in enumerate(self.vertices)}

    def _retained_cells(self) -> List[Tuple[int, int]]:
        """The 8 retained sub-cells of the 3x3 carpet (center removed)."""
        cells = []
        for i in range(3):
            for j in range(3):
                if not (i == 1 and j == 1):
                    cells.append((i, j))
        return cells

    def _build(self, level: int) -> Tuple[List[Tuple[int, int]], List[Tuple[int, int]]]:
        """Build vertex set and edges of the level-m pre-carpet."""
        # grid of side 3^level; remove cells whose base-3 address hits center
        side = 3 ** level
        kept = set()
        for x in range(side):
            for y in range(side):
                if self._is_carpet_point(x, y, level):
                    kept.add((x, y))
        vertices = sorted(kept)
        vset = set(vertices)
        edges = []
        for (x, y) in vertices:
            for dx, dy in ((1, 0), (0, 1)):
                nb = (x + dx, y + dy)
                if nb in vset:
                    edges.append(((x, y), nb))
        return vertices, edges

    def _is_carpet_point(self, x: int, y: int, level: int) -> bool:
        """A point survives iff no base-3 digit pair is (1,1)."""
        for _ in range(level):
            if (x % 3 == 1) and (y % 3 == 1):
                return False
            x //= 3
            y //= 3
        return True

    def adjacency(self) -> Tensor:
        n = len(self.vertices)
        A = torch.zeros(n, n)
        for (a, b) in self.edges:
            i, j = self.index[a], self.index[b]
            A[i, j] = 1.0
            A[j, i] = 1.0
        return A

    def graph_laplacian_matrix(self) -> Tensor:
        A = self.adjacency()
        deg = A.sum(dim=1)
        return torch.diag(deg) - A


class CarpetLaplacianApprox(nn.Module):
    """
    [T1] Discrete carpet Laplacian at a fixed pre-carpet level, with
    resistance renormalization c_m = rho^m.

    This is the COMPUTABLE object. It is NOT the carpet Laplacian; it is
    a finite approximation whose limit (m -> infinity) is the research
    target (Barlow-Bass). We expose the renormalization factor explicitly.
    """

    def __init__(self, level: int = 2, rho: float = 1.25):
        super().__init__()
        self.level = level
        self.rho = rho
        self.graph = PreCarpetGraph(level)
        L = self.graph.graph_laplacian_matrix()
        self.register_buffer("L", L)
        # resistance gauge c_m = rho^m (Consolidated Carpet paper)
        self.register_buffer("c_m", torch.tensor(rho ** level))

    def laplacian(self, u: Tensor) -> Tensor:
        """Apply renormalized discrete Laplacian: c_m * L u."""
        return self.c_m * (self.L @ u)

    def dirichlet_energy(self, u: Tensor) -> Tensor:
        """E_m(u) = c_m * sum_{x~y} (u(x)-u(y))^2 (graph Dirichlet form)."""
        A = self.graph.adjacency().to(u.device)
        diff = u.unsqueeze(0) - u.unsqueeze(1)
        return self.c_m * 0.5 * (A * diff * diff).sum()


