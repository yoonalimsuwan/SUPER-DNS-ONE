# [T2] DIRICHLET-FORM / MOSCO CONVERGENCE SCAFFOLD  (structure only)
# ═══════════════════════════════════════════════════════════════════════

class CarpetDirichletScaffold:
    """
    [T2] Encodes the CHECKABLE consistency requirements the pre-carpet
    energies E_m must satisfy to converge (Mosco) to the carpet Dirichlet
    form, per the Consolidated Carpet paper Theorem 2.

    We implement the diagnostics one can actually compute at finite levels:
      • resistance-growth gauge  rho = lim R_n^{1/n}  (quasi-multiplicative)
      • cross-level energy consistency under coarse-graining
      • the shorting inequality  R_{n+j} >= 3^{-j} R_n

    The actual m->infinity Mosco limit is the RESEARCH GOAL (Barlow-Bass),
    not something this scaffold claims to deliver.
    """

    def __init__(self, max_level: int = 3, rho_init: float = 1.25):
        self.max_level = max_level
        self.rho_init = rho_init
        self.levels = [CarpetLaplacianApprox(level=m, rho=rho_init)
                       for m in range(1, max_level + 1)]

    def resistance_consistency(self) -> Dict[str, float]:
        """
        Check quasi-multiplicativity-style consistency across levels.
        Returns diagnostics; does NOT assert the limit exists.
        """
        # use the renormalization factors as a proxy resistance sequence
        R = [float(lv.c_m) for lv in self.levels]
        report = {"R_levels": R}
        # shorting inequality proxy: R_{n+1}/R_n should be ~ rho
        ratios = [R[i + 1] / R[i] for i in range(len(R) - 1)]
        report["ratios"] = ratios
        report["rho_estimate"] = sum(ratios) / max(len(ratios), 1)
        return report

    def energy_coherence(self, u_fine: Tensor) -> Dict[str, float]:
        """
        Compare Dirichlet energy of a field across two adjacent levels via
        a coarse-graining (restriction). Reports the consistency residual.
        HONEST: this is a finite-level diagnostic, not a proof of Mosco
        convergence.
        """
        if len(self.levels) < 2:
            return {"note": "need >= 2 levels"}
        L1, L2 = self.levels[0], self.levels[1]
        E1 = float(L1.dirichlet_energy(u_fine[: L1.L.shape[0]]))
        E2 = float(L2.dirichlet_energy(u_fine))
        return {"E_coarse": E1, "E_fine": E2, "ratio": E2 / max(E1, 1e-30)}


