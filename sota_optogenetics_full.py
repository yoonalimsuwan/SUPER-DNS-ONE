class PennesBioheatSolver(nn.Module):
    def __init__(self, num_voxels, dz_mm=0.1, dt=1e-3, k=0.5, rho_c=4.0e6,
                 omega_b=0.008, T_arterial=37.0, T_ambient=37.0,
                 cg_iters=8):
        super().__init__()
        self.n = int(num_voxels)
        self.dz = float(dz_mm) * 1e-3
        self.dt = float(dt)
        self.k = float(k); self.rho_c = float(rho_c)
        self.omega_b = float(omega_b)
        self.T_a = float(T_arterial); self.T_amb = float(T_ambient)
        self.cg_iters = int(cg_iters)
        self.register_buffer("inv_dz2", torch.tensor(1.0 / (self.dz ** 2)))

    def _laplacian(self, T):
        Tl = F.pad(T[..., :-1], (1, 0), value=self.T_amb)
        Tr = F.pad(T[..., 1:],  (0, 1), value=self.T_amb)
        return (Tl + Tr - 2.0 * T) * self.inv_dz2

    def forward(self, T_prev, Q_light, dt=None):
        dt = float(self.dt if dt is None else dt)
        D = self.k / self.rho_c
        source = T_prev / dt + self.omega_b * self.T_a + Q_light / self.rho_c
        inv_diag = 1.0 / (1.0 / dt + self.omega_b + 2.0 * D * self.inv_dz2)
        T = T_prev
        for _ in range(self.cg_iters):
            T = (source + D * self._laplacian(T)) * inv_diag
        return T


