class SOTAOptogeneticPipeline(nn.Module):
    """Everything, end-to-end."""

    def __init__(
        self,
        num_neurons: int,
        opsin_specs: Sequence[ExtendedOpsinSpec],
        wavelengths_nm: torch.Tensor,
        dt: float = 1e-3,
        *,
        tissue_layers: Sequence[float] = (0.5, 1.0, 2.0),
        use_monte_carlo: bool = False,
        n_mc_photons: int = 256,
        integrator: str = "expm",
        stochastic: bool = False,
        num_thermal_voxels: int = 32,
        dynamic_ions: bool = True,
    ) -> None:
        super().__init__()
        self.num_neurons = int(num_neurons)
        self.dt = float(dt)

        if use_monte_carlo:
            self.photon = DifferentiableMonteCarloTransport(
                num_layers=len(tissue_layers), depth_mm=tissue_layers,
                n_photons=n_mc_photons,
            )
        else:
            self.photon = AnalyticalPhotonTransport(
                num_layers=len(tissue_layers), depth_mm=tissue_layers,
            )
        self.use_mc = use_monte_carlo

        self.optogenetics = OpsinKineticsEngine(
            num_neurons=num_neurons, opsin_specs=opsin_specs,
            wavelengths_nm=wavelengths_nm, dt=dt,
            integrator="langevin" if stochastic else integrator,
        )
        self.ions = DynamicIonDynamics(num_neurons, dt=dt) \
                    if dynamic_ions else None
        self.nsem = NSEMCoupling(num_neurons, dt=dt)
        self.safety = PhototoxicitySafety(num_neurons, dt=dt)
        self.thermal = PennesBioheatSolver(num_voxels=num_thermal_voxels,
                                            dt=dt)

    # ------------------------------------------------------------------ #
    def initial_state(self, B, *, device=None, dtype=torch.float32):
        s = {
            "v": torch.full((B, self.num_neurons), -65.0,
                            device=device, dtype=dtype),
            "x": self.optogenetics.initial_states(B, device=device, dtype=dtype),
            "T": torch.full((B, self.thermal.n), 37.0,
                            device=device, dtype=dtype),
        }
        if self.ions is not None:
            s["ion"] = self.ions.initial_state(B, device=device, dtype=dtype)
        return s

    @torch.no_grad()
    def reset_safety(self): self.safety.reset()

    def step(self, state, irradiance, i_synaptic, *,
             return_diagnostics=False):
        # L1 — photon transport
        if self.use_mc:
            irr_eff, _deposit = self.photon(irradiance.to(state["v"].dtype))
        else:
            irr_eff = self.photon(irradiance.to(state["v"].dtype))

        # L2 — thermal
        Q_light = irr_eff.sum(dim=-1, keepdim=True) if irr_eff.dim() == 3 \
                  else irr_eff.unsqueeze(-1)
        Q_vox = Q_light.expand(-1, self.thermal.n) * 1e3
        T_next = self.thermal(state["T"], Q_vox)
        T_C = T_next.mean(dim=-1, keepdim=True).expand(-1, self.num_neurons)

        # L3 — opsin kinetics + GHK
        ion_in = state.get("ion") if self.ions is not None else None
        i_photo, x_next, i_ion = self.optogenetics(
            irr_eff, state["v"], state["x"],
            ion_in=ion_in, temperature_C=T_C,
        )

        # L3b — ion dynamics
        ion_next = self.ions(ion_in, i_ion) if self.ions is not None else None

        # L5 — NSEM
        v_next, rate = self.nsem(state["v"], i_synaptic, i_photo)

        # L6 — safety
        if return_diagnostics:
            safety_loss, margin, diag = self.safety(
                irr_eff, temperature_C=T_C, return_diagnostics=True)
        else:
            safety_loss, margin = self.safety(irr_eff, temperature_C=T_C)
            diag = None

        new_state = {"v": v_next, "x": x_next, "T": T_next}
        if ion_next is not None:
            new_state["ion"] = ion_next

        out = {
            "state": new_state,
            "i_photo": i_photo,
            "rate": rate,
            "safety_loss": safety_loss,
            "margin": margin,
        }
        if diag is not None:
            out["diagnostics"] = diag
        return out


