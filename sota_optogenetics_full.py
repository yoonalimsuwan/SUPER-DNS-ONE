# ===================================================================== #
#  L1a — ANALYTICAL PHOTON TRANSPORT  (fast path)
# ===================================================================== #
class AnalyticalPhotonTransport(nn.Module):
    """Beer–Lambert + diffusion approximation with learnable μ_a, μ_s."""

    def __init__(self, num_layers, depth_mm, mu_a_init=0.1,
                 mu_s_init=10.0, anisotropy=0.9):
        super().__init__()
        self.anisotropy = float(anisotropy)
        self.num_layers = int(num_layers)

        def _mk(v, n):
            if isinstance(v, (int, float)):
                v = [float(v)] * n
            t = torch.tensor(list(v), dtype=torch.float32).clamp_min(1e-8)
            return nn.Parameter(torch.log(torch.expm1(t)))

        self.mu_a_raw = _mk(mu_a_init, num_layers)
        self.mu_s_raw = _mk(mu_s_init, num_layers)

        depth = torch.tensor(list(depth_mm), dtype=torch.float32)
        self.register_buffer("cum_depth", depth.cumsum(0))

    @property
    def mu_a(self): return F.softplus(self.mu_a_raw)
    @property
    def mu_s(self): return F.softplus(self.mu_s_raw)

    def forward(self, I0, layer_idx=None):
        mu_a, mu_s = self.mu_a, self.mu_s
        if layer_idx is None:
            z = self.cum_depth[-1]
            w = F.softmax(-self.cum_depth, dim=0)
            mu_a_eff = (w * mu_a).sum()
            mu_s_eff = (w * mu_s).sum()
        else:
            z = self.cum_depth[layer_idx]
            mu_a_eff = mu_a[: layer_idx + 1].mean()
            mu_s_eff = mu_s[: layer_idx + 1].mean()
        mu_s_prime = mu_s_eff * (1.0 - self.anisotropy)
        att = torch.exp(-(mu_a_eff + mu_s_eff) * z)
        dif = (mu_s_prime * z * torch.exp(-mu_a_eff * z)) / (1.0 + mu_s_prime * z)
        return I0 * (att + dif)


