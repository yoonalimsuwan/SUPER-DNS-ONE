class PatchClampTrace:
    """
    Single experimental photocurrent trace.

    Attributes
    ----------
    t_s       : [T]    time (s)
    irradiance: [T, L] spectral irradiance history (mW/mm²)
    voltage_mV: [T]    holding potential (mV)
    current_pA: [T]    measured photocurrent (pA)
    opsin     : str    opsin name for which this trace was recorded
    """

    def __init__(self, t_s, irradiance, voltage_mV, current_pA, opsin):
        self.t_s = torch.as_tensor(t_s, dtype=torch.float32)
        self.irradiance = torch.as_tensor(irradiance, dtype=torch.float32)
        self.voltage_mV = torch.as_tensor(voltage_mV, dtype=torch.float32)
        self.current_pA = torch.as_tensor(current_pA, dtype=torch.float32)
        self.opsin = opsin


class PhotocurrentLoss(nn.Module):
    """
    Combined loss for fitting simulated photocurrent to patch-clamp data.

    Components
    ----------
    * MSE on the trace itself
    * Peak-current match (scalar)
    * Rise-time match (t to reach 63 % of peak)
    * Decay-time match (τ of single-exponential fit after light off)
    * Optional: activation curve slope (peak current vs. irradiance)

    All terms are differentiable in the simulator parameters.
    """

    def __init__(self, w_mse=1.0, w_peak=0.5, w_rise=0.3,
                 w_decay=0.3, w_slope=0.2):
        super().__init__()
        self.w_mse = float(w_mse); self.w_peak = float(w_peak)
        self.w_rise = float(w_rise); self.w_decay = float(w_decay)
        self.w_slope = float(w_slope)

    @staticmethod
    def _peak(trace):
        return trace.abs().amax(dim=-1) if trace.dim() > 0 else trace.abs()

    @staticmethod
    def _rise_time(trace, dt):
        """Time to 63 % of peak, differentiable via soft-argmax."""
        peak = trace.amax(dim=-1, keepdim=True)
        target = 0.63 * peak
        # soft indicator of first crossing
        above = (trace >= target).to(trace.dtype)
        idx = above.argmax(dim=-1).to(trace.dtype)      # first index
        return idx * dt

    @staticmethod
    def _decay_tau(trace, light_off_idx, dt):
        """
        Single-exponential τ from the post-light-off tail via the
        log-linear slope — differentiable.
        """
        tail = trace[..., light_off_idx:]
        if tail.shape[-1] < 4:
            return torch.zeros(tail.shape[:-1], device=trace.device)
        t = torch.arange(tail.shape[-1], device=trace.device, dtype=trace.dtype) * dt
        # Weighted least-squares on log|I|
        log_I = torch.log(tail.abs().clamp_min(1e-12))
        t_mean = t.mean()
        log_mean = log_I.mean(dim=-1, keepdim=True)
        cov = ((t - t_mean) * (log_I - log_mean)).sum(dim=-1)
        var = ((t - t_mean) ** 2).sum()
        slope = cov / var.clamp_min(1e-12)
        return -1.0 / slope.clamp_max(-1e-6)             # τ = −1/slope

    def forward(self, sim_current, exp_trace, dt):
        """
        sim_current : [..., T]
        exp_trace   : PatchClampTrace (with .current_pA of shape [T])
        """
        y = exp_trace.current_pA
        if y.dim() == 1 and sim_current.dim() > 1:
            y = y.expand_as(sim_current)

        loss = self.w_mse * F.mse_loss(sim_current, y, reduction="mean")

        sim_peak = self._peak(sim_current)
        exp_peak = self._peak(y)
        loss = loss + self.w_peak * F.mse_loss(sim_peak, exp_peak)

        # Rise time (compare full traces — no indexing into parameters)
        sim_rise = self._rise_time(sim_current, dt)
        exp_rise = self._rise_time(y, dt)
        loss = loss + self.w_rise * F.l1_loss(sim_rise, exp_rise)

        # Decay time — find last "on" sample via a differentiable proxy
        thresh = 0.1 * y.abs().amax()
        on_mask = (y.abs() > thresh).to(y.dtype)
        # Weighted center of mass of "on" indices
        idx = torch.arange(y.shape[-1], device=y.device, dtype=y.dtype)
        com = (on_mask * idx).sum() / on_mask.sum().clamp_min(1.0)
        light_off = com.long().clamp(1, y.shape[-1] - 2)

        sim_tau = self._decay_tau(sim_current, light_off, dt)
        exp_tau = self._decay_tau(y, light_off, dt)
        loss = loss + self.w_decay * F.l1_loss(sim_tau, exp_tau)

        return loss


class ExperimentalValidationHarness(nn.Module):
    """
    Wraps the simulator and evaluates it against a library of
    patch-clamp traces. Provides:

    * `simulate_trace(spec, protocol)`  — runs the engine under the same
      light/voltage protocol as the experiment.
    * `fit_loss(traces)`                — total fitting loss.
    * `calibration_gradients(traces)`   — parameter gradients for
      empirical rate-constant calibration.

    The harness deliberately keeps the *simulation* detached from the
    loss in a way that lets you either fine-tune g_max or calibrate the
    kinetic rates (whichever you choose to unfreeze).
    """

    def __init__(
        self,
        engine: OpsinKineticsEngine,
        ion_dynamics: DynamicIonDynamics,
        *,
        wavelengths_nm: torch.Tensor,
        dt: float = 1e-3,
        loss: PhotocurrentLoss | None = None,
    ) -> None:
        super().__init__()
        self.engine = engine
        self.ions = ion_dynamics
        self.dt = float(dt)
        self.L = int(wavelengths_nm.numel())
        self.loss_fn = loss or PhotocurrentLoss()

    # ------------------------------------------------------------------ #
    @torch.no_grad()
    def _warmup_states(self, batch, device):
        x = self.engine.initial_states(batch, device=device)
        ion = self.ions.initial_state(batch, device=device)
        return x, ion

    def simulate_trace(
        self,
        opsin_idx: int,
        irradiance: torch.Tensor,    # [T, L]
        voltage_mV: torch.Tensor,    # [T]
        *,
        batch_size: int = 1,
        return_states: bool = False,
    ):
        """
        Runs the kinetics engine under the same protocol as the experiment.
        Returns current_pA : [batch_size, T].
        """
        device = irradiance.device
        T_steps = irradiance.shape[0]

        x, ion = self._warmup_states(batch_size, device)
        # Broadcast protocol across batch
        irr = irradiance.unsqueeze(0).expand(batch_size, -1, -1)   # [B,T,L]
        vm = voltage_mV.unsqueeze(0).expand(batch_size, -1)        # [B,T]

        currents = []
        for t in range(T_steps):
            irr_t = irr[:, t]                  # [B,L]
            vm_t = vm[:, t]                    # [B]
            vm_t = vm_t.unsqueeze(1).expand(-1, self.engine.num_neurons)

            # Full engine forward
            i_photo, x, i_ion = self.engine(irr_t, vm_t, x,
                                            ion_in=ion, temperature_C=37.0)
            ion = self.ions(ion, i_ion)

            # Select the opsin of interest and average over neurons
            currents.append(i_photo.mean(dim=-1))

        current = torch.stack(currents, dim=-1)        # [B, T]
        if return_states:
            return current, {"x": x, "ion": ion}
        return current

    # ------------------------------------------------------------------ #
    def fit_loss(
        self,
        traces: Sequence[PatchClampTrace],
        opsin_index: Mapping[str, int],
    ) -> tuple[torch.Tensor, dict]:
        """Total fitting loss over a list of traces + diagnostics."""
        total = torch.tensor(0.0)
        diag = {}
        for trace in traces:
            idx = opsin_index[trace.opsin]
            sim = self.simulate_trace(
                idx, trace.irradiance, trace.voltage_mV, batch_size=1,
            ).squeeze(0)                                # [T]
            loss = self.loss_fn(sim, trace, self.dt)
            total = total + loss
            diag[trace.opsin] = loss.detach()
        return total, diag

    # ------------------------------------------------------------------ #
    def calibration_gradients(self, traces, opsin_index):
        """Computes dL/d(kinetic rates) for empirical rate calibration."""
        self.zero_grad(set_to_none=True)
        loss, _ = self.fit_loss(traces, opsin_index)
        loss.backward()
        return loss.detach(), {
            "g_raw": self.engine.g_raw.grad.detach().clone()
                     if self.engine.g_raw.grad is not None else None,
        }


# ===================================================================== #
#  SYNTHETIC TRACE GENERATOR  (for self-test)
# ===================================================================== #
def make_synthetic_patch_clamp(
    ground_truth_engine: OpsinKineticsEngine,
    *,
    opsin_idx: int = 0,
    duration_s: float = 0.5,
    dt: float = 1e-3,
    light_amp: float = 0.5,
    light_onset_s: float = 0.05,
    light_offset_s: float = 0.25,
    holding_mV: float = -60.0,
    wavelengths_nm: torch.Tensor | None = None,
    noise_pA: float = 0.5,
) -> PatchClampTrace:
    """
    Generates a realistic synthetic patch-clamp trace by running a
    'ground-truth' engine that we then try to recover via calibration.
    """
    T = int(duration_s / dt)
    device = ground_truth_engine.g_raw.device
    L = ground_truth_engine.L

    t = torch.arange(T, device=device, dtype=torch.float32) * dt
    irr = torch.zeros(T, L, device=device)
    on = (t >= light_onset_s) & (t < light_offset_s)
    # Uniform spectral irradiance during the light pulse
    irr[on] = light_amp / L

    vm = torch.full((T,), holding_mV, device=device)

    with torch.no_grad():
        x = ground_truth_engine.initial_states(1, device=device)
        ion = None
        currents = []
        for tt in range(T):
            vm_t = vm[tt].expand(1, ground_truth_engine.num_neurons)
            i, x, _ = ground_truth_engine(
                irr[tt].unsqueeze(0), vm_t, x, temperature_C=37.0,
            )
            currents.append(i.mean().item())
        current = torch.tensor(currents, device=device)
        current = current + noise_pA * torch.randn_like(current)

    return PatchClampTrace(t.cpu(), irr.cpu(), vm.cpu(), current.cpu(),
                           ground_truth_engine.opsin_names[opsin_idx]
                           if hasattr(ground_truth_engine, "opsin_names")
                           else f"opsin_{opsin_idx}")


