class DynamicIonDynamics(nn.Module):
    """
    Concentration dynamics for intracellular Na⁺, K⁺, Ca²⁺, H⁺.

    Physics
    -------
    For each ion i with valence zᵢ and current Iᵢ (per unit area):

        d[i]ᵢ/dt = −Iᵢ / (zᵢ · F · Vol) + pumps + leaks + buffers

    Na⁺/K⁺-ATPase (3 Na⁺ out : 2 K⁺ in):

        I_pump = I_max · σ([Na]ᵢ / K_Na) · σ([K]ₒ / K_K)

    where σ(x) = x^1.5 / (1 + x^1.5) gives the sigmoidal dependence.

    Ca²⁺ buffering (fast endogenous buffer, rapid-equilibrium):

        d[Ca]ᵢ/dt · (1 + κ_B) = −I_Ca / (2·F·Vol)
        κ_B = B_total · K_d / (K_d + [Ca]ᵢ)²

    H⁺ (pH) buffering with a fixed buffer capacity β:

        d[pH]/dt = −I_H / (F · Vol · β)

    All quantities are differentiable and work in FP16/BF16 (internal FP32).
    """

    def __init__(
        self,
        num_neurons: int,
        dt: float = 1e-3,
        # --- geometry ---
        cell_radius_um: float = 10.0,
        # --- resting concentrations (mM) ---
        Na_rest: float = 12.0,
        K_rest:  float = 140.0,
        Ca_rest: float = 1e-4,
        H_pH_rest: float = 7.2,
        # --- extracellular ---
        Na_out: float = 145.0,
        K_out:  float = 5.0,
        # --- pump ---
        I_pump_max: float = 100.0,       # pA
        K_Na_pump: float = 10.0,         # mM
        K_K_pump:  float = 1.5,          # mM
        # --- Ca buffering ---
        B_total: float = 0.1,            # mM endogenous buffer
        K_d_Ca:  float = 1e-3,           # mM
        Ca_extrusion_tau: float = 50e-3, # s (NCX + PMCA lumped)
        # --- H buffering ---
        beta_H: float = 20.0,            # mM/pH unit
        # --- leak ---
        leak_rate: float = 1e-3,         # s^-1
    ) -> None:
        super().__init__()
        self.num_neurons = int(num_neurons)
        self.dt = float(dt)

        # Intracellular volume (sphere) in liters
        r_m = float(cell_radius_um) * 1e-6
        vol_m3 = 4.0 / 3.0 * math.pi * r_m ** 3
        vol_L = vol_m3 * 1e3
        self.register_buffer("volume_L", torch.tensor(vol_L))

        self.Na_out = float(Na_out); self.K_out = float(K_out)
        self.I_pump_max = float(I_pump_max)
        self.K_Na_pump = float(K_Na_pump); self.K_K_pump = float(K_K_pump)
        self.B_total = float(B_total); self.K_d_Ca = float(K_d_Ca)
        self.Ca_extrusion_tau = float(Ca_extrusion_tau)
        self.beta_H = float(beta_H)
        self.leak_rate = float(leak_rate)

        # Resting values (buffers, not learnable by default)
        self.register_buffer("Na_rest", torch.tensor(float(Na_rest)))
        self.register_buffer("K_rest",  torch.tensor(float(K_rest)))
        self.register_buffer("Ca_rest", torch.tensor(float(Ca_rest)))
        self.register_buffer("H_rest",  torch.tensor(10.0 ** (-float(H_pH_rest))))

    def initial_state(self, B, *, device=None, dtype=torch.float32):
        """Returns [B, N, 4] with (Na, K, Ca, H) in mM."""
        s = torch.empty(B, self.num_neurons, 4, device=device, dtype=dtype)
        s[..., 0] = self.Na_rest
        s[..., 1] = self.K_rest
        s[..., 2] = self.Ca_rest
        s[..., 3] = self.H_rest
        return s

    def forward(self, ion_in, i_per_ion):
        """
        ion_in   : [B,N,4]
        i_per_ion: [B,N,K,4]  from OpsinKineticsEngine (pA per unit area)

        Returns ion_next : [B,N,4]
        """
        d = ion_in.dtype
        ctx = (torch.autocast(device_type=ion_in.device.type, enabled=False)
               if ion_in.device.type in _AUTOCAST
               else contextlib.nullcontext())
        with ctx:
            x = ion_in.float()
            I = i_per_ion.float()

            # Sum over opsins → [B,N,4]
            I_total = I.sum(dim=-2)

            # --- 1. Opsin-mediated flux ---
            # I in pA → C/s ; convert to mol/s via /F
            z = torch.tensor([1.0, 1.0, 2.0, 1.0],
                             device=x.device, dtype=x.dtype)
            F_L = F_FARADAY
            vol = self.volume_L
            # mol/(L·s) = (C/s) / (z · F · V[L]) · 1e-12 (pA→A)
            d_ion_opsin = -I_total * 1e-12 / (z * F_L * vol)

            # --- 2. Na/K-ATPase ---
            Na_i = x[..., 0]; K_o = self.K_out
            sNa = (Na_i / self.K_Na_pump).clamp_min(0.0).pow(1.5)
            sNa = sNa / (1.0 + sNa)
            sK = K_o / (self.K_K_pump + K_o)
            I_pump_pA = self.I_pump_max * sNa * sK        # [B,N]
            # 3 Na out, 2 K in
            d_Na_pump = -3.0 * I_pump_pA * 1e-12 / (F_L * vol)
            d_K_pump  = +2.0 * I_pump_pA * 1e-12 / (F_L * vol)

            d_pump = torch.stack([d_Na_pump, d_K_pump,
                                  torch.zeros_like(d_Na_pump),
                                  torch.zeros_like(d_Na_pump)], dim=-1)

            # --- 3. Passive leak (toward resting) ---
            d_leak = (torch.stack([
                self.Na_rest, self.K_rest, self.Ca_rest, self.H_rest
            ], dim=-1) - x) * self.leak_rate

            # --- 4. Ca buffering + extrusion ---
            Ca = x[..., 2]
            kappa_B = self.B_total * self.K_d_Ca / (self.K_d_Ca + Ca).pow(2)
            ca_extrusion = (Ca - self.Ca_rest) / self.Ca_extrusion_tau
            # effective Ca rate is (flux - extrusion) / (1 + κ_B)
            d_Ca = (d_ion_opsin[..., 2] + d_pump[..., 2] + d_leak[..., 2]
                    - ca_extrusion) / (1.0 + kappa_B).clamp_min(1.0)

            # --- 5. Assemble ---
            d_total = d_ion_opsin + d_pump + d_leak
            # Replace Ca with buffered version
            d_total = torch.cat([
                d_total[..., :2],
                d_Ca.unsqueeze(-1),
                d_total[..., 3:],
            ], dim=-1)

            # H⁺ / pH buffering: divide by β
            d_H = d_total[..., 3] / self.beta_H
            d_total = torch.cat([
                d_total[..., :3],
                d_H.unsqueeze(-1),
            ], dim=-1)

            # Explicit Euler with positivity clamp (concentrations are physical)
            ion_next = (x + self.dt * d_total).clamp_min(1e-8)

        return ion_next.to(d)


