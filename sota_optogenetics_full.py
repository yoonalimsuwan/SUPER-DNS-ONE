#  L3 — OPSIN KINETICS ENGINE  (6-state, GHK, Q10)
# ===================================================================== #
class OpsinKineticsEngine(nn.Module):
    """6-state photocycle + GHK current + Q10 temperature scaling."""

    N_STATES = 6
    STATES = ("C1", "O1", "O2", "P520", "C2", "D")

    def __init__(self, num_neurons, opsin_specs, wavelengths_nm,
                 dt=1e-3, integrator="expm"):
        super().__init__()
        self.num_neurons = int(num_neurons)
        self.K = len(opsin_specs)
        self.L = int(wavelengths_nm.numel())
        self.dt = float(dt)
        self.integrator = integrator

        g_raw = torch.tensor(
            [math.log(math.expm1(max(s.g_max_init, 1e-8))) for s in opsin_specs],
            dtype=torch.float32,
        ).unsqueeze(-1).expand(self.K, self.num_neurons).clone()
        self.g_raw = nn.Parameter(g_raw)

        def _t(vals): return torch.tensor(list(vals), dtype=torch.float32)
        for name in ("gamma", "e12_0", "e21_0", "Gd1", "Gd2", "Gr",
                     "k1", "k2", "kd1", "kd2", "kr", "kP", "kPr",
                     "alpha", "n_photon", "Q10"):
            self.register_buffer(name, _t(getattr(s, name) for s in opsin_specs))
        for name in ("P_Na", "P_K", "P_Ca", "P_H"):
            self.register_buffer(name, _t(getattr(s, name) for s in opsin_specs))
        self.register_buffer("sign", _t(float(s.sign) for s in opsin_specs))
        self.register_buffer("ga1_scale", _t([0.5] * self.K))
        self.register_buffer("ga2_scale", _t([0.1] * self.K))
        self.register_buffer("ion_z", _t([1.0, 1.0, 2.0, 1.0]))

        self.register_buffer("wavelengths_nm", wavelengths_nm.float().clone())
        self.register_buffer(
            "action_spectrum",
            self._build_spectrum(opsin_specs, wavelengths_nm),
        )

    @staticmethod
    def _build_spectrum(specs, lam):
        lam = lam.float()
        rows = [torch.exp(-0.5 * ((lam - s.peak_nm) / s.sigma_nm) ** 2)
                for s in specs]
        rows = [r / r.amax().clamp_min(1e-8) for r in rows]
        return torch.stack(rows, dim=0)

    def initial_states(self, B, *, device=None, dtype=torch.float32):
        x = torch.zeros(B, self.num_neurons, self.K, self.N_STATES,
                        device=device, dtype=dtype)
        x[..., 0] = 1.0
        return x

    @torch.no_grad()
    def get_g_max(self): return F.softplus(self.g_raw)

    # ------------------------------------------------------------------ #
    def forward(self, irradiance, v_membrane, opsin_states,
                ion_in=None, temperature_C=None):
        """
        ion_in : [B,N,4]  intracellular Na/K/Ca/H (mM).  If None, defaults
                 to resting values.
        """
        d_i, d_x = v_membrane.dtype, opsin_states.dtype
        ctx = (torch.autocast(device_type=v_membrane.device.type, enabled=False)
               if v_membrane.device.type in _AUTOCAST
               else contextlib.nullcontext())

        with ctx:
            irr = irradiance.float()
            vm = v_membrane.float()
            x = opsin_states.float()

            if temperature_C is None:
                T_C = torch.full_like(vm, 37.0)
            elif isinstance(temperature_C, (int, float)):
                T_C = torch.full_like(vm, float(temperature_C))
            else:
                T_C = temperature_C.float()

            if ion_in is None:
                ion_in = torch.tensor([12.0, 140.0, 1e-4, 1e-4],
                                       device=vm.device, dtype=torch.float32)
                ion_in = ion_in.view(1, 1, 4).expand(*vm.shape, 4)
            else:
                ion_in = ion_in.float()

            q10_factor = self.Q10.unsqueeze(-1).pow(
                (T_C.unsqueeze(-1) - 37.0) / 10.0)               # [B,N,K]

            if irr.dim() == 2:
                irr = irr.unsqueeze(1)
            eff = torch.einsum("bnl,kl->bnk", irr, self.action_spectrum)
            eff = eff.clamp_min(0.0).pow(self.n_photon) * self.alpha

            Ga1 = self.ga1_scale * eff
            Ga2 = self.ga2_scale * eff
            e12 = (self.e12_0 + self.k1 * eff) * q10_factor
            e21 = (self.e21_0 + self.k2 * eff) * q10_factor

            if self.integrator == "expm":
                x_next = self._step_expm(x, Ga1, Ga2, e12, e21)
            elif self.integrator == "rk4":
                x_next = self._step_rk4(x, Ga1, Ga2, e12, e21)
            else:
                x_next = self._step_langevin(x, Ga1, Ga2, e12, e21)

            O1, O2, P = x_next[..., 1], x_next[..., 2], x_next[..., 3]
            g_open = O1 + self.gamma * O2 + 0.5 * P

            i_ghk, i_per_ion = self._ghk_current(vm, T_C, ion_in)
            g_max_bnk = F.softplus(self.g_raw).T.unsqueeze(0)
            i_k = g_max_bnk * g_open * i_ghk                    # [B,N,K]
            i_photo = (i_k * self.sign).sum(dim=-1)

            # Per-ion current (for L3b ion dynamics) — [B,N,K,4]
            i_ion_k = g_max_bnk.unsqueeze(-1) * g_open.unsqueeze(-1) * i_per_ion

        return i_photo.to(d_i), x_next.to(d_x), i_ion_k.to(d_i)

    # ------------------------------------------------------------------ #
    def _ghk_current(self, vm, T_C, ion_in):
        """
        Returns total GHK current [B,N,K] and per-ion contribution [B,N,K,4].
        """
        T_K = (T_C + 273.15).clamp_min(1.0)
        F_RT = F_FARADAY / (R_GAS * T_K)
        V_term = vm.unsqueeze(-1) * F_RT.unsqueeze(-1)          # [B,N,1]

        z = self.ion_z                                         # [4]
        c_out = torch.tensor([145.0, 5.0, 2.0, 4e-5],
                             device=vm.device).view(1, 1, 4)
        c_in = ion_in                                          # [B,N,4]

        zV = z.view(1, 1, 4) * V_term                          # [B,N,4]
        exp_neg = torch.exp(-zV)
        numer = c_out - c_in * exp_neg
        denom = 1.0 - exp_neg

        eps = 1e-6
        safe = denom.abs() > eps
        per_ion = torch.where(safe,
                              numer / denom.clamp_min(eps) * denom.sign(),
                              c_out - c_in)

        prefactor = (z.view(1, 1, 4) ** 2) * V_term * F_FARADAY   # [B,N,4]
        P_ions = torch.stack([self.P_Na, self.P_K, self.P_Ca, self.P_H],
                             dim=-1)                                # [K,4]
        P_ions = P_ions.unsqueeze(0).unsqueeze(0)                   # [1,1,K,4]

        contrib = prefactor.unsqueeze(2) * per_ion.unsqueeze(2)     # [B,N,1,4]
        i_per_ion = P_ions * contrib                                # [B,N,K,4]
        i_total = i_per_ion.sum(dim=-1) * 1e-6                      # [B,N,K]
        return i_total, i_per_ion * 1e-6

    # ------------------------------------------------------------------ #
    def _build_generator(self, Ga1, Ga2, e12, e21):
        B, N, K = Ga1.shape
        M = Ga1.new_zeros(B, N, K, self.N_STATES, self.N_STATES)
        M[..., 0, 0] = -Ga1
        M[..., 1, 0] =  Ga1
        M[..., 0, 1] =  self.Gd1
        M[..., 1, 1] = -(self.Gd1 + e12 + self.kd1)
        M[..., 2, 1] =  e12
        M[..., 5, 1] =  self.kd1
        M[..., 1, 2] =  e21
        M[..., 2, 2] = -(e21 + self.kP + self.kd2)
        M[..., 3, 2] =  self.kP
        M[..., 5, 2] =  self.kd2
        M[..., 2, 3] =  self.kPr * 0.1
        M[..., 3, 3] = -(self.kPr * 0.1 + self.Gd2 + self.kPr * 0.9)
        M[..., 4, 3] =  self.kPr * 0.9
        M[..., 0, 4] =  self.Gr
        M[..., 4, 4] = -self.Gr
        M[..., 0, 5] =  self.kr
        M[..., 5, 5] = -self.kr
        return M

    def _step_expm(self, x, Ga1, Ga2, e12, e21):
        M = self._build_generator(Ga1, Ga2, e12, e21)
        P = torch.linalg.matrix_exp(M * self.dt)
        return torch.einsum("bnkij,bnkj->bnki", P, x)

    def _step_rk4(self, x, Ga1, Ga2, e12, e21):
        M = self._build_generator(Ga1, Ga2, e12, e21)
        dt = self.dt
        f = lambda y: torch.einsum("bnkij,bnkj->bnki", M, y)
        k1 = f(x); k2 = f(x + 0.5*dt*k1); k3 = f(x + 0.5*dt*k2); k4 = f(x + dt*k3)
        return x + (dt/6.0)*(k1 + 2*k2 + 2*k3 + k4)

    def _step_langevin(self, x, Ga1, Ga2, e12, e21, omega=1e3):
        M = self._build_generator(Ga1, Ga2, e12, e21)
        drift = torch.einsum("bnkij,bnkj->bnki", M, x) * self.dt
        noise_scale = torch.sqrt(torch.clamp(x / omega, min=0.0) * self.dt)
        x_next = x + drift + noise_scale * torch.randn_like(x)
        return x_next / x_next.sum(dim=-1, keepdim=True).clamp_min(1e-8)


